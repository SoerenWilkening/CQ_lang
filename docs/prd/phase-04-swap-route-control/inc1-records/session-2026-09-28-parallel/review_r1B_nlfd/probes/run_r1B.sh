#!/bin/bash
# run_r1B.sh — reproduces every row of review_r1B_nlfd/REVIEW.md.
#   Binaries: O = ORACLE main 9a230646 (frozen), S = SUBJECT 3626a38d, C = 3626a38d + c7dad811 (rhk5 r2),
#   R = c7dad811 alone. C and R are COPIES under <scratchpad>/r1B_bin (never relinked under a measurement).
#   Each `.c` is built with build.sh (the run_slice_multi.sh recipe: CQ TU -include CQ.h, lib TU without,
#   clang -O1, llvm-link); each row = rv.sh (lower; rc from cq-opt itself; 2b STRICT + CENSUS; link; run).
#   eq.sh = byte compare + rhk5's tools/trace_twin_equiv.py (read from the rhk5 worktree).
H=$(cd "$(dirname "$0")" && pwd)
row() { d=$1; n=$2; t=$3; a=$4; (cd $H/$d && echo "$d/$n $t a=$a: $($H/rv.sh $t $n $a 2>/dev/null)"); }
build() { (cd $H/$1 && for n in "${@:2}"; do $H/build.sh $n >/dev/null || echo "BUILD-FAIL $1/$n"; done); }
# Q1 — the drop at a musttail site under each LLVM-19 musttail rule (IR, generated by q1/gen.py)
(cd $H/q1 && python3 gen.py >/dev/null)
for v in plain inreg tailcc swtailcc byval diamond qdiamond; do for s in "" N T; do for t in O S; do row q1 q1_$v$s.ll $t 5; done; done; done
# Q2 — the demotion
build q2 c4 c4N c4T d1 d2 d2m d3 f1 f1N f1T f2 f2N f2T i1 i1N i1T n1 n1N b1 b1N b1T
for n in c4 c4N c4T d1 d2 d2m d3 b1 b1N b1T; do for t in O S C; do row q2 $n.s1.ll $t 5; done; done
for n in f1 f1N f1T f2 f2N f2T i1 i1N i1T n1 n1N; do for t in O S; do row q2 $n.s1.ll $t 5; done; done
for t in O S C; do row q2 pa2.ll $t 5; done
# Q3 — the rhk5-routed probes (implementer's sources, copied to impl/)
build impl mtl mtlN mtlT ev7 ev7N ev7T ev9 ev9N ev9T
for n in mtl mtlN mtlT ev7 ev7N ev7T ev9 ev9N ev9T; do for t in O S C R; do row impl $n.s1.ll $t 5; done; done
for t in S C; do for n in mtl mtlN mtlT ev7 ev7N ev7T ev9 ev9N ev9T; do (cd $H/impl && $H/rv.sh $t $n.s1.ll 5 >/dev/null 2>&1); done
  for p in "mtl mtlT" "mtl mtlN" "ev7 ev7T" "ev7 ev7N" "ev9 ev9T" "ev9 ev9N"; do $H/eq.sh $t $p; done; done
# Q4 — s82e / qjoc spellings
build q4 s1 s1N s1T s1R s2 s2N s2T j1 j1N j1T
for n in s1 s1N s1T s1R s2 s2N s2T j1 j1N j1T; do for t in O S; do row q4 $n.s1.ll $t 3; done; done
