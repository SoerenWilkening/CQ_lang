#!/usr/bin/env python3
"""bd ziuw — emit a pure call chain deep enough to have blown the C++ stack.

`isSpeculatablePureCalleeBodyImpl` used to be a mutual C++ recursion with the
body walk, one machine frame per call-graph node.  At ~37.5k nodes it exhausted
the 8MB main-thread stack: rc=132 (SIGILL), ZERO stderr, no diagnostic, on BOTH
`cq-opt` and stock `opt`.  *** A CRASH IS NOT A DECLINE *** — the Prime
Directive's loud reject never happened.  The walk is now an explicit worklist,
so the only bound is heap.

The generator lives here rather than as a committed `.ll` because the witness is
~60k functions (~5MB of textual IR) and its only interesting property is its
LENGTH.  Regenerating it costs ~0.2s; committing it would cost every `git grep`
and every editor in the tree.

    gen_deep_pure_chain.py <depth> <accept|decline|twin>

  accept   every body is speculatable; the strict walk returns TRUE and the 6.5
           classical-call arm lowers.
  decline  the LEAF reads constant memory, which strict mode refuses (bd wve8
           deferred clause 1) and the speculation-safe twin refuses too (batch
           053).  The verdict is FALSE and the region loud-declines.  This is the
           half that matters: it is the exact reject the crash used to pre-empt.
           (It was a conditional-branch leaf until batch 053 froze such a
           condition in a twin, dm7f.29.)
  twin     (bd dm7f.21) the LEAF returns `add nsw` under `noundef`, so every level
           of the chain is hoisted as its speculation-safe twin
           (control_classical_call_arm_twin_accept_deep_chain.ll).

Both flavours run through the STRICT entry point (`isSpeculatableTotalCallee`,
S6) because that is the one bd 9hea routed 6.5 acceptance through, i.e. the
widest reachable input class.  The counter triple is printed by
`CQ_PREDMUX_COUNT` and is what the fixture asserts on: an exit code would say
the module lowered, never WHICH gate lowered it.
"""
import sys

D = int(sys.argv[1])
MODE = sys.argv[2] if len(sys.argv) > 2 else "accept"
assert MODE in ("accept", "decline", "twin"), MODE

out = [
    "; GENERATED by ir-pass/test/Inputs/gen_deep_pure_chain.py — do not edit.",
    "declare i32 @cq_theta_si32(i32, double)",
    "declare i32 @cq_measure_si32(i32)",
]
for i in range(D):
    out += [
        "define i32 @f_%d(i32 %%a) #0 {" % i,
        "  %%s = call i32 @f_%d(i32 %%a)" % (i + 1),
        "  ret i32 %s",
        "}",
    ]
if MODE == "accept":
    out += [
        "define i32 @f_%d(i32 %%a) #0 {" % D,
        "  %s = add i32 %a, 100",
        "  ret i32 %s",
        "}",
    ]
elif MODE == "twin":
    # bd dm7f.21: the leaf's `nsw` poison reaches its own `noundef` return, so
    # every level needs a speculation-safe twin: the poison dataflow and the twin
    # builder must both walk D levels without the C++ stack.
    out += [
        "define noundef i32 @f_%d(i32 %%a) #0 {" % D,
        "  %s = add nsw i32 %a, 100",
        "  ret i32 %s",
        "}",
    ]
else:
    # A read of CONSTANT memory: `memory(none)`-consistent, refused by the strict
    # walk (a deferred-bounds memory op) AND by the twin's totality walk (batch
    # 053, TwinTotality.h: no memory). The chain above it is untouched, so the
    # FALSE has to travel all D levels back to the root — which is precisely the
    # unwind the recursive version could not perform without a stack. (Until
    # batch 053 this leaf was a conditional branch; the twin now freezes that
    # condition, so a branch leaf lowers as a D-deep twin chain.)
    out = out[:3] + ["@cq.deep.tab = internal constant i32 7"] + out[3:]
    out += [
        "define i32 @f_%d(i32 %%a) #0 {" % D,
        "  %v = load i32, ptr @cq.deep.tab",
        "  %s = add i32 %v, %a",
        "  ret i32 %s",
        "}",
    ]
out += [
    "",
    "; The Phase-6.5 classical-call arm: an all-classical-argument pure call in a",
    "; tainted-condition diamond. It hoists the call, so it needs TOTALITY and runs",
    "; the walk in strict mode.",
    "define void @example(i32 %u0, i32 %arg) {",
    "entry:",
    "  %q = call i32 @cq_theta_si32(i32 %u0, double 2.500000e-01)",
    "  %cnd = icmp sgt i32 %q, 3",
    "  br i1 %cnd, label %arm, label %merge",
    "arm:",
    "  %r = call i32 @f_0(i32 %arg)",
    "  br label %merge",
    "merge:",
    "  %y = phi i32 [ %r, %arm ], [ 5, %entry ]",
    "  %m = call i32 @cq_measure_si32(i32 %y)",
    "  ret void",
    "}",
    "attributes #0 = { nounwind willreturn memory(none) }",
]
sys.stdout.write("\n".join(out) + "\n")
