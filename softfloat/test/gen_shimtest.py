#!/usr/bin/env python3
"""Generate shimtest.c: every float template of a group (softfloat/build/manifest.json), called through its
shim, the LOWERED library and an integer-only toy backend, against the same root built natively.

    gen_shimtest.py OUT.c [--group default|f80|all] [--samples N]

Per symbol and sample: operand rails are allocated with the input values (a literal operand is passed as a
literal, a _rm mode as a literal, a _rmq mode as a rail); the forward template's result rail must hold the
native root's value (cqsfi_*, the integer-only inner function, called on the same bit patterns); the _unc
template must return that rail to 0. The toy backend separately counts dirty frees inside the library.
An INT_X conversion (manifest "x") is checked against its root built natively from cq/cqsf_roots_x.ll,
through the entry cqsft_<root>(operand, mode, result); an iN operand wider than 128 bits is passed in
uint64_t parts, as LLVM passes it.
"""
import json
import sys
from pathlib import Path

SF = Path(__file__).resolve().parent.parent
BITS = {"f16": 16, "bf16": 16, "f32": 32, "f64": 64, "f80": 80}
UT = {16: "uint16_t", 32: "uint32_t", 64: "uint64_t", 80: "u128"}
LIT = {"f16": "_Float16", "bf16": "__bf16", "f32": "float", "f64": "double", "f80": "long double"}
X80 = "struct extFloat80M"
FE = [0, 1024, 2048, 3072]


def int_ct(n, signed):
    if n == 1:
        return "bool"
    if n in (8, 16, 32, 64):
        return f"{'' if signed else 'u'}int{n}_t"
    return f"{'' if signed else 'unsigned '}_BitInt({n})"


def wide_args(n, v):
    """An iN value (u256 expression) as the C arguments of a call: N/64 parts above 128 bits."""
    if n > 128:
        return ", ".join(f"(uint64_t)({v} >> {64 * j})" for j in range((n + 63) // 64))
    return f"({int_ct(n, True)}){v}"


def wide_params(n):
    return ", ".join(["uint64_t"] * ((n + 63) // 64)) if n > 128 else int_ct(n, True)


def main():
    a = sys.argv[1:]
    out = a[0]
    group = a[a.index("--group") + 1] if "--group" in a else "default"
    samples = int(a[a.index("--samples") + 1]) if "--samples" in a else 12
    man = json.loads((SF / "build" / "manifest.json").read_text())
    roots = {}
    for line in (SF / "cq" / "cqsf_inner.c").read_text().splitlines():
        if line.startswith(("uint", "int", "bool", "struct", "unsigned", "_BitInt", "signed")) and "cqsfi_" in line and line.endswith("{"):
            name = line[line.index("cqsfi_"):line.index("(")]
            roots[name] = line[:line.index(" cqsfi_")]
    c = ["""/* Generated by softfloat/test/gen_shimtest.py: do not edit. */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
typedef unsigned __int128 u128;
typedef unsigned _BitInt(256) u256;
u128 toy_val(int32_t h);
u256 toy_val256(int32_t h);
void cqrt_free(int32_t h);
int32_t cqrt_alloc_i1(bool); int32_t cqrt_alloc_i8(int8_t); int32_t cqrt_alloc_i16(int16_t); int32_t cqrt_alloc_i32(int32_t);
int32_t cqrt_alloc_i64(int64_t); int32_t cqrt_alloc_f16(_Float16); int32_t cqrt_alloc_bf16(__bf16); int32_t cqrt_alloc_f32(float);
int32_t cqrt_alloc_f64(double); int32_t cqrt_alloc_f80(long double);
struct extFloat80M { uint64_t signif; uint16_t signExp; };
static struct extFloat80M x80(u128 v) { return (struct extFloat80M){(uint64_t)v, (uint16_t)(v >> 64)}; }
static u128 x80v(struct extFloat80M a) { return (u128)a.signif | ((u128)a.signExp << 64); }
static uint64_t rng = 0x243F6A8885A308D3u;
static uint64_t rnd(void) { rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return rng; }
static long ncalls, nbad, nunc;
static const char *cur;
/* an input: a special value or a value of tame exponent, as a bit pattern of the format */
static uint64_t fpin(int bits, int ebits) {
    int fb = bits - 1 - ebits; uint64_t s = (uint64_t)1 << (bits - 1), e = (((uint64_t)1 << ebits) - 1) << fb;
    uint64_t one = (((uint64_t)1 << (ebits - 1)) - 1) << fb, q = (uint64_t)1 << (fb - 1);
    uint64_t sp[] = {0, 1, one, one | 1, e - 1, e, e | q, e | 1, q, one + ((uint64_t)3 << fb), one - ((uint64_t)1 << fb) /* 0.5 */};
    uint64_t r = rnd();
    if (r % 3 == 0) return sp[(r >> 8) % (sizeof sp / sizeof sp[0])] | ((r >> 40) & 1 ? s : 0);
    uint64_t bias = ((uint64_t)1 << (ebits - 1)) - 1; int spread = ebits >= 8 ? 30 : 8;
    uint64_t ex = bias + (uint64_t)((int)(rnd() % (2 * spread + 1)) - spread);
    return ((rnd() & 1) ? s : 0) | (ex << fb) | (rnd() & (q * 2 - 1));
}
/* an f80 input (significand | sign-exponent << 64): specials, non-canonical encodings, tame exponents */
static u128 fpin80(void) {
    static const uint64_t sm[] = {0, 1, 0x8000000000000000u, 0x8000000000000001u, 0xC000000000000000u, 0xFFFFFFFFFFFFFFFFu,
                                  0x4000000000000000u, 0x8000000000000005u};
    static const uint16_t se[] = {0, 0x3FFF, 0x7FFE, 0x7FFF, 0x403E, 0x3FFE, 1};
    uint64_t r = rnd();
    if (r % 3 == 0) return (u128)sm[(r >> 8) % 8] | ((u128)(se[(r >> 16) % 7] | ((r >> 40) & 1 ? 0x8000 : 0)) << 64);
    uint16_t e = (uint16_t)(0x3FFF + (int)(rnd() % 61) - 30) | ((rnd() & 1) ? 0x8000 : 0);
    return (u128)(rnd() | 0x8000000000000000u) | ((u128)e << 64);
}
static void bad(const char *what, u256 got, u256 want) {
    nbad++;
    if (nbad <= 20) printf("MISMATCH %s: %s got %#llx:%016llx want %#llx:%016llx\\n", cur, what, (unsigned long long)(got >> 64),
                           (unsigned long long)got, (unsigned long long)(want >> 64), (unsigned long long)want);
}
/* an N-bit integer input: random bits with a random number of leading zeros, or their complement */
static u256 intin(int n) {
    u256 v = 0;
    for (int k = 0; k < 4; k++) v = (v << 64) | (u256)rnd();
    switch (rnd() % 4) { case 0: break; case 1: v >>= rnd() % 256; break; case 2: v = ~(v >> (rnd() % 256)); break;
    default: v = (u256)1 << (rnd() % n); }
    return n >= 256 ? v : v & (((u256)1 << n) - 1);
}
"""]
    tests = []
    for sym, m in sorted(man.items()):
        if group != "all" and m["group"] != group:
            continue
        if m.get("kind"):
            c.append(ftest(len(tests), sym, m, samples))
            tests.append(sym)
            continue
        if m.get("x"):
            c.append(xtest(len(tests), sym, m, samples))
            tests.append(sym)
            continue
        root = "cqsfi_" + m["root"][5:]
        ins = [tuple(k) for k in m["ins"]]
        shape = m["shape"] or ""
        n = len(ins)
        letters = ["h"] * n if not shape else ["h" if ch in "hq" else "l" for ch in shape]
        rw = 32 if m["exc"] else (BITS[m["out"][1]] if m["out"][0] == "fp" else m["out"][1])
        f = [f"static void t_{len(tests)}(void) {{", f"    cur = \"{sym}\";"]
        f.append(f"    for (int s = 0; s < {samples}; s++) {{")
        decl_args, shim_args, frees, root_args = [], [], [], []
        for i, (k, l) in enumerate(zip(ins, letters)):
            if k[0] == "fp":
                w = k[1]
                b = BITS[w]
                if w == "f80":
                    f.append(f"        u128 v{i} = fpin80();")
                    root_args.append(f"x80(v{i})")
                else:
                    eb = {"f16": 5, "bf16": 8, "f32": 8, "f64": 11}[w]
                    f.append(f"        {UT[b]} v{i} = ({UT[b]})fpin({b}, {eb});")
                    root_args.append(f"v{i}")
                nb = 10 if w == "f80" else f"sizeof x{i}"
                if l == "h":
                    f.append(f"        {LIT[w]} x{i} = 0; memcpy(&x{i}, &v{i}, {nb}); int32_t h{i} = cqrt_alloc_{w}(x{i});")
                    shim_args.append(f"h{i}"); frees.append(f"h{i}")
                else:
                    f.append(f"        {LIT[w]} x{i} = 0; memcpy(&x{i}, &v{i}, {nb});")
                    shim_args.append(f"x{i}")
            else:
                nb, signed = k[1], k[2]
                if sym.startswith("cq_template_is_fpclass"):
                    f.append(f"        uint32_t v{i} = (uint32_t)(rnd() & 0x3FF);")
                    root_args.append(f"v{i}")
                    shim_args.append(f"(int32_t)v{i}")
                    continue
                ct = int_ct(nb, signed)
                expr = "(rnd() & 1)" if nb == 1 else f"({ct})(rnd() >> (rnd() % 64))"
                f.append(f"        {ct} v{i} = {expr};")
                root_args.append(f"v{i}")
                if l == "h":
                    f.append(f"        int32_t h{i} = cqrt_alloc_i{nb}(v{i});")
                    shim_args.append(f"h{i}"); frees.append(f"h{i}")
                else:
                    shim_args.append(f"v{i}")
        mode_needed = len(roots_params(roots, root)) > n
        if m["rm"] or mode_needed:
            f.append(f"        uint32_t mo = {'(uint32_t)(rnd() % 4) * 1024u' if m['rm'] else '0'};")
            if mode_needed:
                root_args.append("mo")
            if m["rm"] == "_rm":
                shim_args.append("(int32_t)mo")
            elif m["rm"] == "_rmq":
                f.append("        int32_t hm = cqrt_alloc_i32((int32_t)mo);")
                shim_args.append("hm"); frees.append("hm")
        rt = roots[root]
        call = f"{root}({', '.join(root_args)})"
        if rt == X80:
            call = f"x80v({call})"
        f.append(f"        u256 want = (u256)({call}) & (((u256)1 << {rw}) - 1);")
        f.append(f"        int32_t o = {sym}({', '.join(shim_args)});")
        f.append("        ncalls++;")
        f.append("        if (toy_val256(o) != want) bad(\"value\", toy_val256(o), want);")
        f.append(f"        {sym}_unc({', '.join(['o'] + shim_args)});")
        f.append("        if (toy_val256(o) != 0) { nunc++; bad(\"_unc\", toy_val256(o), 0); }")
        f.append("        cqrt_free(o);")
        for h in reversed(frees):
            f.append(f"        cqrt_free({h});")
        f.append("    }\n}")
        proto_params = []
        for i, (k, l) in enumerate(zip(ins, letters)):
            if l == "h":
                proto_params.append("int32_t")
            elif k[0] == "fp":
                proto_params.append(LIT[k[1]])
            elif sym.startswith("cq_template_is_fpclass"):
                proto_params.append("int32_t")
            else:
                proto_params.append(int_ct(k[1], True) if k[1] != 1 else "bool")
        if m["rm"]:
            proto_params.append("int32_t")
        c.append(f"int32_t {sym}({', '.join(proto_params)});\nvoid {sym}_unc(int32_t, {', '.join(proto_params)});")
        c.append(f"{rt} {root}({', '.join(roots_params(roots, root))});")
        c.append("\n".join(f))
        tests.append(sym)
    c.append("int main(void) {")
    for i in range(len(tests)):
        c.append(f"    t_{i}();")
    c.append(f'    printf("shimtest: %d template symbols, %ld calls, %ld mismatches (%ld _unc not 0)\\n", {len(tests)}, ncalls, nbad, nunc);')
    c.append("    return nbad != 0;\n}")
    Path(out).write_text("\n".join(c) + "\n")
    print(f"gen_shimtest: {len(tests)} symbols, {samples} samples each")


def xtest(idx, sym, m, samples):
    """An INT_X template: one operand (iN or fp), the native root through cqsft_*."""
    k = tuple(m["ins"][0])
    shape = m["shape"] or ""
    lit_ = shape == "l"
    rw = 32 if m["exc"] else (BITS[m["out"][1]] if m["out"][0] == "fp" else m["out"][1])
    f = [f"void cqsft_{m['root'][5:]}(const void *, uint32_t, void *);"]
    if k[0] == "int":
        n = k[1]
        pp = wide_params(n)
    else:
        n = None
        pp = LIT[k[1]]
    proto = ["int32_t" if not lit_ else pp] + (["int32_t"] if m["rm"] else [])
    f.append(f"int32_t {sym}({', '.join(proto)});\nvoid {sym}_unc(int32_t, {', '.join(proto)});")
    f += [f"static void t_{idx}(void) {{", f"    cur = \"{sym}\";", f"    for (int s = 0; s < {samples}; s++) {{",
          "        unsigned char ib[32] = {0}, ob[32] = {0};"]
    if n is not None:
        f.append(f"        u256 v = intin({n}); memcpy(ib, &v, 32);")
        harg = f"cqrt_alloc_i{n}({wide_args(n, 'v')})"
        larg = wide_args(n, "v")
        f.append(f"        int32_t cqrt_alloc_i{n}({pp});")
    else:
        w = k[1]
        if w == "f80":
            f.append("        u128 v = fpin80(); memcpy(ib, &v, 10);")
        else:
            eb = {"f16": 5, "bf16": 8, "f32": 8, "f64": 11}[w]
            f.append(f"        u256 v = fpin({BITS[w]}, {eb}); memcpy(ib, &v, {BITS[w] // 8});")
        f.append(f"        {LIT[w]} x = 0; memcpy(&x, ib, {10 if w == 'f80' else BITS[w] // 8});")
        harg, larg = f"cqrt_alloc_{w}(x)", "x"
    f.append(f"        uint32_t mo = {'(uint32_t)(rnd() % 4) * 1024u' if m['rm'] else '0'};")
    args = []
    frees = []
    if lit_:
        args.append(larg)
    else:
        f.append(f"        int32_t h = {harg};")
        args.append("h"); frees.append("h")
    if m["rm"] == "_rm":
        args.append("(int32_t)mo")
    elif m["rm"] == "_rmq":
        f.append("        int32_t hm = cqrt_alloc_i32((int32_t)mo);")
        args.append("hm"); frees.append("hm")
    f.append(f"        cqsft_{m['root'][5:]}(ib, mo, ob);")
    f.append(f"        u256 want = 0; memcpy(&want, ob, 32); want &= ((u256)1 << {rw}) - 1;")
    f.append(f"        int32_t o = {sym}({', '.join(args)});")
    f.append("        ncalls++;")
    f.append("        if (toy_val256(o) != want) bad(\"value\", toy_val256(o), want);")
    f.append(f"        {sym}_unc({', '.join(['o'] + args)});")
    f.append("        if (toy_val256(o) != 0) { nunc++; bad(\"_unc\", toy_val256(o), 0); }")
    f.append("        cqrt_free(o);")
    for h in reversed(frees):
        f.append(f"        cqrt_free({h});")
    f.append("    }\n}")
    return "\n".join(f)


def ftest(idx, sym, m, samples):
    """select/bitcast at a float width (a forwarding shim, no root): select is c ? a : b on the bit
    patterns, bitcast the same bits."""
    f, proto, args, frees = [], [], [], []
    body = [f"static void t_{idx}(void) {{", f"    cur = \"{sym}\";", f"    for (int s = 0; s < {samples}; s++) {{"]

    def operand(i, k, lit_):
        if k[0] == "int":
            n = k[1]
            if n == 1:
                body.append(f"        u256 v{i} = rnd() & 1; int32_t h{i} = cqrt_alloc_i1((bool)v{i});")
            else:
                body.append(f"        u256 v{i} = intin({n}); int32_t h{i} = cqrt_alloc_i{n}(({int_ct(n, True)})v{i});")
                f.append(f"int32_t cqrt_alloc_i{n}({int_ct(n, True)});")
            proto.append("int32_t"); args.append(f"h{i}"); frees.append(f"h{i}")
            return
        w = k[1]
        if w == "f80":
            body.append(f"        u256 v{i} = fpin80();")
        else:
            eb = {"f16": 5, "bf16": 8, "f32": 8, "f64": 11}[w]
            body.append(f"        u256 v{i} = fpin({BITS[w]}, {eb});")
        body.append(f"        {LIT[w]} x{i} = 0; memcpy(&x{i}, &v{i}, {10 if w == 'f80' else BITS[w] // 8});")
        if lit_:
            proto.append(LIT[w]); args.append(f"x{i}")
        else:
            body.append(f"        int32_t h{i} = cqrt_alloc_{w}(x{i});")
            proto.append("int32_t"); args.append(f"h{i}"); frees.append(f"h{i}")

    ins = [tuple(k) for k in m["ins"]]
    if m["kind"] == "select":
        letters = m["shape"] or "hh"
        operand(0, ins[0], False)
        operand(1, ins[1], letters[0] == "l")
        operand(2, ins[2], letters[1] == "l")
        want = "(v0 ? v1 : v2)"
    else:
        operand(0, ins[0], False)
        want = "v0"
    out = tuple(m["out"])
    rw = BITS[out[1]] if out[0] == "fp" else out[1]
    body.append(f"        u256 want = {want} & (((u256)1 << {rw}) - 1);")
    body.append(f"        int32_t o = {sym}({', '.join(args)});")
    body.append("        ncalls++;")
    body.append("        if (toy_val256(o) != want) bad(\"value\", toy_val256(o), want);")
    body.append(f"        {sym}_unc({', '.join(['o'] + args)});")
    body.append("        if (toy_val256(o) != 0) { nunc++; bad(\"_unc\", toy_val256(o), 0); }")
    body.append("        cqrt_free(o);")
    for h in reversed(frees):
        body.append(f"        cqrt_free({h});")
    body.append("    }\n}")
    f.append(f"int32_t {sym}({', '.join(proto)});\nvoid {sym}_unc(int32_t, {', '.join(proto)});")
    return "\n".join(f + body)


_INNER = None


def roots_params(roots, root):
    """The C parameter types of an inner root, from its definition line in cq/cqsf_inner.c."""
    global _INNER
    if _INNER is None:
        _INNER = (SF / "cq" / "cqsf_inner.c").read_text()
    text = _INNER
    i = text.index(f" {root}(")
    sig = text[i + len(root) + 2:text.index(")", i)]
    return [p.rsplit(" ", 1)[0] for p in sig.split(", ") if p]


if __name__ == "__main__":
    main()
