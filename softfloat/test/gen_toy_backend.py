#!/usr/bin/env python3
"""Generate a toy classical backend that implements INTEGER templates only (BACKEND_ABI §1, §2.2-§2.8).

    gen_toy_backend.py OUT.c LOWERED.ll... [--library-manifest softfloat/build/manifest.json]

A rail is a slot holding one basis value (up to 256 bits); Ry and phases are not applied (the test
programs rotate by 0). An iN argument with N > 128 is taken as N/64 uint64_t parts, as LLVM passes it
(C would pass a _BitInt(N) in memory): in the next integer registers when all parts fit, else all on the
stack with the remaining integer registers skipped (measured, LLVM 19 x86-64), which C spells as one dummy
uint64_t per skipped register and a struct of the parts by value. A freed handle is reused only after 2^20 later frees, so a use of
a recently freed rail is still caught. Every cqrt_* and integer cq_template_* that the given lowered modules declare is
generated from its declaration. fneg, fabs and copysign are bit
operations on fp widths and are generated as such. Every other floating-point template is NOT generated: it must come from the
lowered SoftFloat library (libqsoftfloat.a); one the library does not provide stops the generator.
The backend also checks what it can see: a rail freed while not 0 that is no untouched seed (a dirty
free), a pop of an empty stack, a use of a freed rail. It prints the counts at exit and exits 3 on any.
"""
import json
import re
import sys
from pathlib import Path

INT_OPS = {"add", "sub", "mul", "udiv", "sdiv", "urem", "srem", "and", "or", "xor", "shl", "lshr", "ashr",
           "icmp", "select", "zext", "sext", "trunc", "bitcast", "abs", "smax", "smin", "umax", "umin",
           "usub_sat", "uadd_sat", "ssub_sat", "sadd_sat", "ctlz", "cttz", "ctpop", "bswap", "bitreverse",
           "fshl", "fshr", "fneg", "fabs", "copysign"}
BITOPS = {"fneg", "fabs", "copysign", "bitcast", "select"}   # on fp widths too: bit wiring, no float circuit
PREDS = "eq|ne|ugt|uge|ult|ule|sgt|sge|slt|sle"
W_RE = r"i\d+|f16|bf16|f32|f64|f80"
TMPL = re.compile(rf"^cq_template_(?P<op>[a-z_]+?)(?:_(?P<pred>{PREDS}|o[a-z]+|u[a-z]+|ord|uno))?_(?P<w>{W_RE})"
                  rf"(?:_to_(?P<w2>{W_RE}))?(?:_(?P<shape>[hlq]+))?(?P<rm>_rmq?)?(?P<exc>_exc)?(?P<unc>_unc)?$")


def bits(w):
    return {"f16": 16, "bf16": 16, "f32": 32, "f64": 64, "f80": 80}.get(w) or int(w[1:])


CT = {"i1": "_Bool", "i8": "int8_t", "i16": "int16_t", "i32": "int32_t", "i64": "int64_t", "i128": "__int128",
      "half": "_Float16", "bfloat": "__bf16", "float": "float", "double": "double", "x86_fp80": "long double"}


def ctype(t):
    t = t.strip()
    if t in CT:
        return CT[t]
    m = re.fullmatch(r"i(\d+)", t)
    if m:
        return f"_BitInt({m.group(1)})" if int(m.group(1)) > 1 else "_Bool"
    raise SystemExit(f"gen_toy_backend: no C type for {t}")


def wide(t):
    """The number of uint64_t parts of an iN parameter with N > 128, else 0."""
    m = re.fullmatch(r"i(\d+)", t.strip())
    return (int(m.group(1)) + 63) // 64 if m and int(m.group(1)) > 128 else 0


def gprs(t):
    """The integer argument registers an IR parameter type takes (x86-64 SysV as LLVM assigns them)."""
    t = t.strip()
    if t in ("half", "bfloat", "float", "double", "x86_fp80"):
        return 0
    m = re.fullmatch(r"i(\d+)", t)
    return (int(m.group(1)) + 63) // 64 if m else 1


def cparam(t, name, used=0):
    """A literal parameter's C declaration (several for a wide integer); used: the integer argument
    registers taken by the parameters before it."""
    k = wide(t)
    if k and used + k > 6:
        return ", ".join([f"uint64_t {name}_pad{j}" for j in range(6 - used)] + [f"W{k} {name}"])
    if k:
        return ", ".join(f"uint64_t {name}_{j}" for j in range(k))
    return f"{ctype(t)} {name}"


def litv(t, name, used=0):
    """A literal parameter of IR type t as its bit pattern (uv)."""
    k = wide(t)
    if k and used + k > 6:
        return "(" + " | ".join(f"((uv){name}.w[{j}] << {64 * j})" for j in range(k)) + ")"
    if k:
        return "(" + " | ".join(f"((uv){name}_{j} << {64 * j})" for j in range(k)) + ")"
    return lit(ctype(t), name)


def lit(ctyp, name):
    """A literal parameter as its bit pattern (uv)."""
    if ctyp in ("_Float16", "__bf16", "float", "double", "long double"):
        n = {"_Float16": 2, "__bf16": 2, "float": 4, "double": 8, "long double": 10}[ctyp]
        return f"lbits(&{name}, {n})"
    return f"(uv)(unsigned __int128)({name})"


def parse_decls(files):
    decls = {}
    for f in files:
        for m in re.finditer(r"^declare\s+(?:\w+\s+)*?(\S+)\s+@((?:cqrt|cq_template)_\w+)\(([^)]*)\)", Path(f).read_text(), re.M):
            ret, name, params = m.group(1), m.group(2), m.group(3)
            ps = [re.sub(r"\b(signext|zeroext|noundef|nonnull|range\([^)]*\))\b", "", p).strip().split()[0]
                  for p in params.split(",") if p.strip()]
            decls[name] = (ret, ps)
    return decls


PRE = r"""/* Generated by softfloat/test/gen_toy_backend.py: a toy classical backend, integer templates only. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
typedef unsigned __int128 u128;
typedef unsigned _BitInt(256) uv;
typedef _BitInt(256) sv;
typedef struct { uint64_t w[4]; } W4;   /* a 256-bit (or narrower wide) literal passed on the stack */
typedef struct { uint64_t w[3]; } W3;
typedef struct { uv v; int16_t w; char seed, freed; } Rail;
static Rail *R; static int nR = 1, capR;
static long nfree, ndirty, nuse_freed, npop_empty, ntmpl;
static int32_t stk[1 << 20]; static int sp;
#define FQ (1 << 20)
static int32_t fq[FQ], *reuse; static long fqn, fqh, nreuse, capreuse;   /* freed handles, reused after FQ more frees */
static uv M(int w) { return w >= 256 ? ~(uv)0 : (((uv)1 << w) - 1); }
static void report(void) {
    fprintf(stderr, "toy backend: %d rails, %ld template calls, %ld frees, %ld dirty frees, %ld uses of a freed rail, "
            "%ld pops of an empty stack, %d words left on the stack\n", nR - 1, ntmpl, nfree, ndirty, nuse_freed, npop_empty, sp);
    fflush(stdout);
    if (ndirty || nuse_freed || npop_empty) _exit(3);
}
static int32_t fresh(int w, uv v, int seed) {
    if (!capR) atexit(report);
    int32_t h;
    if (nreuse) h = reuse[--nreuse];
    else {
        if (nR >= capR) { capR = capR ? 2 * capR : 1 << 16; R = realloc(R, (size_t)capR * sizeof *R); }
        h = nR++;
    }
    R[h].v = v & M(w); R[h].w = (int16_t)w; R[h].seed = (char)seed; R[h].freed = 0; return h;
}
static uv val(int32_t h) { if (h <= 0 || h >= nR) { fprintf(stderr, "toy: bad handle %d\n", h); abort(); } if (R[h].freed) nuse_freed++; return R[h].v; }
u128 toy_val(int32_t h);   /* for the tests: the basis value a rail holds (the low 128 bits; toy_val256 all) */
u128 toy_val(int32_t h) { return (u128)val(h); }
uv toy_val256(int32_t h);
uv toy_val256(int32_t h) { return val(h); }
static void wr(int32_t h, uv x) { val(h); R[h].v = x & M(R[h].w); R[h].seed = 0; }
static uv lbits(const void *p, int n) { uv x = 0; memcpy(&x, p, (size_t)n); return x; }
static sv sx(uv x, int w) { return w >= 256 ? (sv)x : (sv)(x << (256 - w)) >> (256 - w); }
/* ops on W-bit values */
static uv shamt(uv k, int w) { return k % (uv)w; }
static uv op_bin(const char *op, uv a, uv b, int w) {
    uv m = M(w);
    if (!strcmp(op, "add")) return (a + b) & m;
    if (!strcmp(op, "sub")) return (a - b) & m;
    if (!strcmp(op, "mul")) return (a * b) & m;
    if (!strcmp(op, "udiv")) return b ? a / b : m;
    if (!strcmp(op, "urem")) return b ? a % b : a;
    if (!strcmp(op, "sdiv")) { sv x = sx(a, w), y = sx(b, w); if (!y) return (uv)(x >= 0 ? (sv)-1 : (sv)1) & m;
        if (y == -1) return (uv)(-x) & m; return (uv)(x / y) & m; }
    if (!strcmp(op, "srem")) { sv x = sx(a, w), y = sx(b, w); if (!y) return a; if (y == -1) return 0; return (uv)(x % y) & m; }
    if (!strcmp(op, "and")) return a & b;
    if (!strcmp(op, "or")) return a | b;
    if (!strcmp(op, "xor")) return a ^ b;
    if (!strcmp(op, "shl")) return (a << shamt(b, w)) & m;
    if (!strcmp(op, "lshr")) return a >> shamt(b, w);
    if (!strcmp(op, "ashr")) return (uv)(sx(a, w) >> shamt(b, w)) & m;
    if (!strcmp(op, "smax")) return sx(a, w) >= sx(b, w) ? a : b;
    if (!strcmp(op, "smin")) return sx(a, w) <= sx(b, w) ? a : b;
    if (!strcmp(op, "umax")) return a >= b ? a : b;
    if (!strcmp(op, "umin")) return a <= b ? a : b;
    if (!strcmp(op, "usub_sat")) return a >= b ? a - b : 0;
    if (!strcmp(op, "uadd_sat")) return (a + b) > m ? m : a + b;
    if (!strcmp(op, "sadd_sat") || !strcmp(op, "ssub_sat")) {
        sv r = !strcmp(op, "sadd_sat") ? sx(a, w) + sx(b, w) : sx(a, w) - sx(b, w);
        sv hi = (sv)(M(w - 1)), lo = -hi - 1; return (uv)(r > hi ? hi : r < lo ? lo : r) & m; }
    fprintf(stderr, "toy: no binary op %s\n", op); abort();
}
static uv op_cmp(const char *p, uv a, uv b, int w) {
    sv x = sx(a, w), y = sx(b, w);
    if (!strcmp(p, "eq")) return a == b; if (!strcmp(p, "ne")) return a != b;
    if (!strcmp(p, "ugt")) return a > b; if (!strcmp(p, "uge")) return a >= b;
    if (!strcmp(p, "ult")) return a < b; if (!strcmp(p, "ule")) return a <= b;
    if (!strcmp(p, "sgt")) return x > y; if (!strcmp(p, "sge")) return x >= y;
    if (!strcmp(p, "slt")) return x < y; if (!strcmp(p, "sle")) return x <= y;
    fprintf(stderr, "toy: no predicate %s\n", p); abort();
}
static uv op_un(const char *op, uv a, int w, int w2) {
    uv m = M(w), r = 0;
    if (!strcmp(op, "zext") || !strcmp(op, "bitcast") || !strcmp(op, "trunc")) return a & M(w2);
    if (!strcmp(op, "sext")) return (uv)sx(a, w) & M(w2);
    if (!strcmp(op, "abs")) { sv x = sx(a, w); return (uv)(x < 0 ? -x : x) & m; }
    if (!strcmp(op, "ctlz")) { int n = 0; for (int i = w - 1; i >= 0 && !((a >> i) & 1); i--) n++; return (uv)n; }
    if (!strcmp(op, "cttz")) { int n = 0; for (int i = 0; i < w && !((a >> i) & 1); i++) n++; return (uv)n; }
    if (!strcmp(op, "ctpop")) { int n = 0; for (int i = 0; i < w; i++) n += (int)((a >> i) & 1); return (uv)n; }
    if (!strcmp(op, "bitreverse")) { for (int i = 0; i < w; i++) if ((a >> i) & 1) r |= (uv)1 << (w - 1 - i); return r; }
    if (!strcmp(op, "bswap")) { for (int i = 0; i < w / 8; i++) r |= ((a >> (8 * i)) & 0xFF) << (8 * (w / 8 - 1 - i)); return r; }
    fprintf(stderr, "toy: no unary op %s\n", op); abort();
}
static uv op_fsh(const char *op, uv a, uv b, uv k, int w) {
    unsigned s = (unsigned)(k % (uv)w); uv m = M(w);
    if (!s) return !strcmp(op, "fshl") ? a : b;
    return !strcmp(op, "fshl") ? (((a << s) | (b >> (w - s))) & m) : (((a << (w - s)) | (b >> s)) & m);
}
/* the core gates */
void cqrt_free(int32_t h) {
    val(h); nfree++; if (R[h].v && !R[h].seed) ndirty++; R[h].freed = 1;
    if (fqn == FQ) {   /* the oldest freed handle becomes reusable */
        if (nreuse >= capreuse) { capreuse = capreuse ? 2 * capreuse : 1 << 16; reuse = realloc(reuse, (size_t)capreuse * sizeof *reuse); }
        reuse[nreuse++] = fq[fqh]; fq[fqh] = h; fqh = (fqh + 1) % FQ;
    } else fq[(fqh + fqn++) % FQ] = h;
}
void cqrt_push(int32_t w) { stk[sp++] = w; }
int32_t cqrt_pop(void) { if (!sp) { npop_empty++; return 0; } return stk[--sp]; }
int32_t cqrt_qram_alloc_i8(int32_t n) { return fresh(8, (uv)n, 1); }
void cqrt_not_i1(int32_t h) { wr(h, val(h) ^ 1); }
void cqrt_and_i1(int32_t a, int32_t b, int32_t t) { wr(t, val(t) ^ (val(a) & val(b))); }
void cqrt_or_i1(int32_t a, int32_t b, int32_t t) { wr(t, val(t) ^ (val(a) | val(b))); }
void cqrt_xor_i1(int32_t a, int32_t t) { wr(t, val(t) ^ val(a)); }
void cqrt_rz_i1(int32_t f, double th) { (void)val(f); (void)th; }
void cqrt_invert_begin(void) { fprintf(stderr, "toy: cq_invert is not modelled\n"); abort(); }
void cqrt_invert_end(void) { abort(); }
"""

FP_LIT_C = {"f16": "_Float16", "bf16": "__bf16", "f32": "float", "f64": "double", "f80": "long double"}


def core(name, ret, ps):
    """A core gate from its declaration, or None when it is in PRE."""
    if name in ("cqrt_free", "cqrt_push", "cqrt_pop", "cqrt_qram_alloc_i8", "cqrt_not_i1", "cqrt_and_i1",
                "cqrt_or_i1", "cqrt_xor_i1", "cqrt_rz_i1", "cqrt_invert_begin", "cqrt_invert_end"):
        return None
    m = re.fullmatch(rf"cqrt_(alloc|copy|xorc|measure|ry)_({W_RE})((?:_qangle)?)((?:_controlled)?)", name)
    if not m:
        raise SystemExit(f"gen_toy_backend: no model for {name}")
    op, w, qa, ctl = m.groups()
    n = bits(w)
    if op == "alloc":
        return f"int32_t {name}({cparam(ps[0], 'x')}) {{ return fresh({n}, {litv(ps[0], 'x')}, 1); }}\n"
    if op == "copy":
        if ctl:
            return f"void {name}(int32_t c, int32_t s, int32_t d) {{ if (val(c)) wr(d, val(d) ^ val(s)); }}\n"
        return f"void {name}(int32_t s, int32_t d) {{ wr(d, val(d) ^ val(s)); }}\n"
    if op == "xorc":
        if ctl:
            return f"void {name}(int32_t c, int32_t h, {cparam(ps[-1], 'x')}) {{ if (val(c)) wr(h, val(h) ^ {litv(ps[-1], 'x')}); }}\n"
        return f"void {name}(int32_t h, {cparam(ps[-1], 'x')}) {{ wr(h, val(h) ^ {litv(ps[-1], 'x')}); }}\n"
    if op == "measure":
        if wide(ret):
            raise SystemExit(f"gen_toy_backend: no model for {name} (a result wider than 128 bits)")
        t = ctype(ret)
        return f"{t} {name}(int32_t h) {{ uv v = val(h); {t} r; memcpy(&r, &v, sizeof r); return r; }}\n"
    # ry: Ry is not applied (the test rotates by 0)
    params = ", ".join((["int32_t c"] if ctl else []) + ["int32_t h"] + (["int32_t a"] if qa else ["double th"]))
    return f"void {name}({params}) {{ (void)h; }}\n"


def template(name, ret, ps):
    m = TMPL.match(name)
    if not m:
        raise SystemExit(f"gen_toy_backend: cannot parse {name}")
    op, pred, w, w2, shape, rm, exc, unc = m.group("op", "pred", "w", "w2", "shape", "rm", "exc", "unc")
    if op not in INT_OPS or rm or exc or (op not in BITOPS and (w[0] != "i" or (w2 and w2[0] != "i"))):
        return "fp"
    n, n2 = bits(w), bits(w2) if w2 else None
    args = ps[1:] if unc else ps
    names = [f"p{i}" for i in range(len(args))]
    cparams = []
    # which data operands are literals (shape letters; select: the arms after the condition)
    ndata = {"select": 2, "fshl": 3, "fshr": 3}.get(op, 1 if op in ("zext", "sext", "trunc", "bitcast", "abs", "ctlz",
                                                                   "cttz", "ctpop", "bitreverse", "bswap", "fneg", "fabs") else 2)
    letters = list(shape) if shape else ["h"] * ndata
    first = 1 if op == "select" else 0
    vals = []
    used = 1 if unc else 0
    for i, (t, a) in enumerate(zip(args, names)):
        is_lit = i >= first and letters[i - first] == "l"
        cparams.append(cparam(t, a, used) if is_lit else f"int32_t {a}")
        vals.append(f"({litv(t, a, used)} & M({n}))" if is_lit else f"val({a})")
        k = gprs(t) if is_lit else 1
        used = 6 if (wide(t) and is_lit and used + k > 6) else min(6, used + k)
    if op == "icmp":
        expr, rw = f"op_cmp(\"{pred}\", {vals[0]}, {vals[1]}, {n})", 1
    elif op == "select":
        expr, rw = f"(val(p0) ? {vals[1]} : {vals[2]})", n
    elif op in ("fshl", "fshr"):
        expr, rw = f"op_fsh(\"{op}\", {vals[0]}, {vals[1]}, {vals[2]}, {n})", n
    elif op in ("fneg", "fabs"):
        sb = f"((uv)1 << {n - 1})"
        expr, rw = (f"({vals[0]} ^ {sb})" if op == "fneg" else f"({vals[0]} & ~{sb})"), n
    elif op == "copysign":
        sb = f"((uv)1 << {n - 1})"
        expr, rw = f"(({vals[0]} & ~{sb}) | ({vals[1]} & {sb}))", n
    elif ndata == 1:
        expr, rw = f"op_un(\"{op}\", {vals[0]}, {n}, {n2 or n})", n2 or n
    else:
        expr, rw = f"op_bin(\"{op}\", {vals[0]}, {vals[1]}, {n})", n
    if unc:
        return f"void {name}(int32_t o, {', '.join(cparams)}) {{ ntmpl++; wr(o, val(o) ^ {expr}); }}\n"
    return f"int32_t {name}({', '.join(cparams)}) {{ ntmpl++; return fresh({rw}, {expr}, 0); }}\n"


def main():
    a = sys.argv[1:]
    man = None
    if "--library-manifest" in a:
        i = a.index("--library-manifest")
        man = json.loads(Path(a[i + 1]).read_text())
        del a[i:i + 2]
    out, files = a[0], a[1:]
    decls = parse_decls(files)
    # what the shims call (cq/cqsf_shims.c declares them in C, not in IR)
    for w, t in [("i1", "i1"), ("i8", "i8"), ("i16", "i16"), ("i32", "i32"), ("i64", "i64"), ("f16", "half"),
                 ("bf16", "bfloat"), ("f32", "float"), ("f64", "double"), ("f80", "x86_fp80")]:
        decls.setdefault(f"cqrt_alloc_{w}", ("i32", [t]))
        decls.setdefault(f"cqrt_copy_{w}", ("void", ["i32", "i32"]))
    for m in (man or {}).values():   # the integer widths of the library's templates (the INT_X conversions)
        for k in m["ins"] + [m["out"]]:
            if k[0] == "int":
                decls.setdefault(f"cqrt_alloc_i{k[1]}", ("i32", [f"i{k[1]}"]))
                decls.setdefault(f"cqrt_copy_i{k[1]}", ("void", ["i32", "i32"]))
    body, fp, nint = [PRE], [], 0
    for name in sorted(decls):
        ret, ps = decls[name]
        if name.startswith("cqrt_"):
            c = core(name, ret, ps)
            if c:
                body.append(c)
            continue
        c = template(name, ret, ps)
        if c == "fp":
            fp.append(name)
        else:
            body.append(c)
            nint += 1
    missing = [s for s in fp if man is None or s.removesuffix("_unc") not in man]
    if missing:
        raise SystemExit("gen_toy_backend: floating-point templates the library does not provide: " + " ".join(missing))
    Path(out).write_text("".join(body))
    print(f"gen_toy_backend: {nint} integer templates (forward and _unc) generated; {len(fp)} float templates "
          f"left to the library")


if __name__ == "__main__":
    main()
