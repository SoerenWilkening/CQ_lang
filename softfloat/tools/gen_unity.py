#!/usr/bin/env python3
"""Write softfloat/cq/sf_unity.h: every vendored SoftFloat file as one translation unit.

Left out: 8086-SSE/softfloat_raiseFlags.c (a macro after the patch) and every primitive that
primitives.h already defines INLINE (platform.h's INLINE_LEVEL 5)."""
import re
from pathlib import Path

SF = Path(__file__).resolve().parent.parent
up = SF / "upstream"
inline = set(re.findall(r"INLINE\b[^;{(]*?\b(softfloat_\w+)\s*\(", (up / "include" / "primitives.h").read_text()))
lines = ["/* Generated by softfloat/tools/gen_unity.py: the vendored SoftFloat files as one unit. */"]
for p in sorted(up.glob("*.c")) + sorted((up / "8086-SSE").glob("*.c")):
    name = "softfloat_" + p.stem[2:] if p.stem.startswith("s_") else p.stem
    if p.name == "softfloat_raiseFlags.c" or name in inline:
        continue
    lines.append(f'#include "../{p.relative_to(SF).as_posix()}"')
(SF / "cq" / "sf_unity.h").write_text("\n".join(lines) + "\n")
print(f"gen_unity.py: {len(lines) - 1} files")
