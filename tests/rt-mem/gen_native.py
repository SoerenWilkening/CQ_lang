#!/usr/bin/env python3
"""Generate the native side of the rt-mem differential test (cq-w0-rt-mem).

Writes <out>/native.ll (the LLVM IR memory operations a QROM / QRAM access stands for, compiled by
clang-19 -O1 for the corpus triple) and <out>/native_table.h (the per-width function table the
harness iterates). Per width T:
  nat_store_<w>(ptr t, i64 i, ptr src)    t[i] = *src             (getelementptr T)
  nat_load_<w>(ptr t, i64 i, ptr dst)     *dst = t[i]
  nat_aos_store_<w>(ptr t, i64 i, ptr src) t[i].f = *src           (%S = { i8, T, i16 }, field 1)
  nat_aos_load_<w>(ptr t, i64 i, ptr dst)  *dst = t[i].f
  nat_aos_layout_<w>(ptr t, ptr out)       out[0] = offsetof(S, f), out[1] = sizeof(S), out[2] = sizeof(T)
"""
import os
import sys

# Every width the corpus uses (BACKEND_ABI §0: i1 i7 i8 i16 i32 i64 i80 i100 i128 f16 f32 f64 f80), plus i136.
WIDTHS = [
    ("i1", "i1", 1, "i"), ("i7", "i7", 7, "i"), ("i8", "i8", 8, "i"), ("i16", "i16", 16, "i"),
    ("i32", "i32", 32, "i"), ("i64", "i64", 64, "i"), ("i80", "i80", 80, "i"), ("i100", "i100", 100, "i"),
    ("i128", "i128", 128, "i"), ("i136", "i136", 136, "i"),  # i136: alloc above i128 (any N)
    ("f16", "half", 16, "f"), ("f32", "float", 32, "f"), ("f64", "double", 64, "f"),
    ("f80", "x86_fp80", 80, "f"),
]


def ir() -> str:
    out = ['target datalayout = "e-m:o-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-f80:128-n8:16:32:64-S128"',
           'target triple = "x86_64-apple-macosx"', ""]
    for tok, ty, _, _ in WIDTHS:
        out.append(f"%S.{tok} = type {{ i8, {ty}, i16 }}")
    out.append("")
    for tok, ty, _, _ in WIDTHS:
        out.append(f"""define void @nat_store_{tok}(ptr %t, i64 %i, ptr %src) {{
  %v = load {ty}, ptr %src
  %p = getelementptr {ty}, ptr %t, i64 %i
  store {ty} %v, ptr %p
  ret void
}}
define void @nat_load_{tok}(ptr %t, i64 %i, ptr %dst) {{
  %p = getelementptr {ty}, ptr %t, i64 %i
  %v = load {ty}, ptr %p
  store {ty} %v, ptr %dst
  ret void
}}
define void @nat_aos_store_{tok}(ptr %t, i64 %i, ptr %src) {{
  %v = load {ty}, ptr %src
  %p = getelementptr %S.{tok}, ptr %t, i64 %i, i32 1
  store {ty} %v, ptr %p
  ret void
}}
define void @nat_aos_load_{tok}(ptr %t, i64 %i, ptr %dst) {{
  %p = getelementptr %S.{tok}, ptr %t, i64 %i, i32 1
  %v = load {ty}, ptr %p
  store {ty} %v, ptr %dst
  ret void
}}
define void @nat_aos_layout_{tok}(ptr %t, ptr %out) {{
  %b = ptrtoint ptr %t to i64
  %f = getelementptr %S.{tok}, ptr %t, i64 0, i32 1
  %fi = ptrtoint ptr %f to i64
  %n = getelementptr %S.{tok}, ptr %t, i64 1
  %ni = ptrtoint ptr %n to i64
  %e = getelementptr {ty}, ptr %t, i64 1
  %ei = ptrtoint ptr %e to i64
  %off = sub i64 %fi, %b
  %sz = sub i64 %ni, %b
  %es = sub i64 %ei, %b
  store i64 %off, ptr %out
  %o1 = getelementptr i64, ptr %out, i64 1
  store i64 %sz, ptr %o1
  %o2 = getelementptr i64, ptr %out, i64 2
  store i64 %es, ptr %o2
  ret void
}}
""")
    return "\n".join(out)


def header() -> str:
    h = ["/* Generated by gen_native.py (cq-w0-rt-mem). */", "#include <stdint.h>",
         "typedef void (*nat_fn)(void *, int64_t, void *);",
         "typedef void (*nat_layout_fn)(void *, int64_t *);"]
    for tok, _, _, _ in WIDTHS:
        for f in ("store", "load", "aos_store", "aos_load"):
            h.append(f"void nat_{f}_{tok}(void *, int64_t, void *);")
        h.append(f"void nat_aos_layout_{tok}(void *, int64_t *);")
    h.append("typedef struct { const char *tok; uint32_t bits; char kind; nat_fn store, load, aos_store, aos_load; "
             "nat_layout_fn layout; } nat_width;")
    h.append("static const nat_width NAT_WIDTHS[] = {")
    for tok, _, bits, kind in WIDTHS:
        h.append(f'  {{"{tok}", {bits}, \'{kind}\', nat_store_{tok}, nat_load_{tok}, nat_aos_store_{tok}, '
                 f"nat_aos_load_{tok}, nat_aos_layout_{tok}}},")
    h.append("};")
    h.append(f"#define NAT_NWIDTHS {len(WIDTHS)}")
    return "\n".join(h) + "\n"


def main() -> int:
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "native.ll"), "w") as f:
        f.write(ir())
    with open(os.path.join(out, "native_table.h"), "w") as f:
        f.write(header())
    return 0


if __name__ == "__main__":
    sys.exit(main())
