#!/usr/bin/env python3
"""Generate the native reference for the tmpl-bits differential test (cq-w0-tmpl-bits).

Writes <out>.ll: for every op and width W, the LLVM IR operation itself, wrapped as
    void @nat_<op>_<W>(ptr a, ptr b, ptr c, ptr o)
that loads each operand as i<64*ceil(W/64)>, truncates to i<W>, applies the operation, zero-extends
and stores to o. clang-19 -O1 compiles it to host x86-64 code. For shl/lshr/ashr, where LLVM gives
poison at an amount >= W, a second wrapper @tab_<op>_<W> applies the CR §2 row literally:
`urem k, W` (natively) then the shift. Writes <out>.h: the table the C harness iterates.
"""
import sys

# Every corpus width (BACKEND_ABI §0: i1 i7 i8 i16 i32 i64 i80 i100 i128) plus widths that exercise
# word boundaries and multi-word code (generic in W).
WIDTHS = [1, 3, 7, 8, 16, 32, 63, 64, 65, 80, 100, 127, 128, 129, 200]

BINARY = ["and", "or", "xor"]
SHIFTS = ["shl", "lshr", "ashr"]
FUNNEL = ["fshl", "fshr"]
UNARY = ["bswap", "ctlz", "cttz", "ctpop"]


def words(w):
    return (w + 63) // 64


def wrapper(name, w, arity, body):
    wr = 64 * words(w)
    t = f"i{w}"
    lines = [f"define void @{name}(ptr %pa, ptr %pb, ptr %pc, ptr %po) {{"]
    for i, (p, v) in enumerate([("pa", "a"), ("pb", "b"), ("pc", "c")][:arity]):
        lines.append(f"  %{v}w = load i{wr}, ptr %{p}, align 8")
        if wr == w:
            lines.append(f"  %{v} = add {t} %{v}w, 0")
        else:
            lines.append(f"  %{v} = trunc i{wr} %{v}w to {t}")
    lines += ["  " + l for l in body]
    if wr == w:
        lines.append(f"  store {t} %r, ptr %po, align 8")
    else:
        lines.append(f"  %rw = zext {t} %r to i{wr}")
        lines.append(f"  store i{wr} %rw, ptr %po, align 8")
    lines.append("  ret void")
    lines.append("}")
    return "\n".join(lines)


def main():
    out = sys.argv[1]
    ll, decls, rows = [], set(), []
    for w in WIDTHS:
        t = f"i{w}"
        for op in BINARY:
            ll.append(wrapper(f"nat_{op}_{w}", w, 2, [f"%r = {op} {t} %a, %b"]))
            rows.append((op, w, 2, -1, f"nat_{op}_{w}", "0"))
        for op in SHIFTS:
            ll.append(wrapper(f"nat_{op}_{w}", w, 2, [f"%r = {op} {t} %a, %b"]))
            ll.append(wrapper(f"tab_{op}_{w}", w, 2, [f"%s = urem {t} %b, {w}", f"%r = {op} {t} %a, %s"]))
            rows.append((op, w, 2, 1, f"nat_{op}_{w}", f"tab_{op}_{w}"))
        for op in FUNNEL:
            if w <= 128:
                decls.add(f"declare {t} @llvm.{op}.{t}({t}, {t}, {t})")
                body = [f"%r = call {t} @llvm.{op}.{t}({t} %a, {t} %b, {t} %c)"]
            else:
                # LLVM 19's x86 backend cannot legalize the urem inside llvm.fshl/fshr above 128
                # bits ("Unsupported library call operation"), so above 128 the wrapper spells the
                # LangRef definition in IR (an IR-level urem is expanded before isel).
                hi, lo = ("shl", "lshr") if op == "fshl" else ("lshr", "shl")
                x, y = ("a", "b") if op == "fshl" else ("b", "a")
                body = [f"%s = urem {t} %c, {w}", f"%x = {hi} {t} %{x}, %s", f"%n = sub {t} {w}, %s",
                        f"%y = {lo} {t} %{y}, %n", f"%o = or {t} %x, %y", f"%z = icmp eq {t} %s, 0",
                        f"%r = select i1 %z, {t} %{x}, {t} %o"]
            ll.append(wrapper(f"nat_{op}_{w}", w, 3, body))
            rows.append((op, w, 3, 2, f"nat_{op}_{w}", "0"))
        for op in UNARY:
            if op == "bswap" and w % 16:
                # LLVM defines llvm.bswap only for a multiple of 16 bits (the verifier rejects the
                # rest); BACKEND_ABI §2.8 likewise. The harness checks the evaluator rejects these.
                rows.append((op, w, 1, -1, "0", "0"))
                continue
            if op in ("ctlz", "cttz"):
                decls.add(f"declare {t} @llvm.{op}.{t}({t}, i1)")
                body = [f"%r = call {t} @llvm.{op}.{t}({t} %a, i1 false)"]
            else:
                decls.add(f"declare {t} @llvm.{op}.{t}({t})")
                body = [f"%r = call {t} @llvm.{op}.{t}({t} %a)"]
            ll.append(wrapper(f"nat_{op}_{w}", w, 1, body))
            rows.append((op, w, 1, -1, f"nat_{op}_{w}", "0"))

    with open(out + ".ll", "w") as f:
        f.write('target triple = "x86_64-apple-macosx"\n\n')
        f.write("\n\n".join(ll))
        f.write("\n\n" + "\n".join(sorted(decls)) + "\n")

    with open(out + ".h", "w") as f:
        f.write("/* generated by gen_native.py; do not edit */\n")
        f.write("typedef void (*nat_fn)(const uint64_t *, const uint64_t *, const uint64_t *, uint64_t *);\n")
        names = sorted({r[4] for r in rows if r[4] != "0"} | {r[5] for r in rows if r[5] != "0"})
        for n in names:
            f.write(f"void {n}(const uint64_t *, const uint64_t *, const uint64_t *, uint64_t *);\n")
        f.write("static const struct row { const char *op; uint32_t w; int arity; int amount; nat_fn nat; nat_fn tab; } ROWS[] = {\n")
        for op, w, ar, am, nat, tab in rows:
            f.write(f'  {{"{op}", {w}, {ar}, {am}, {nat}, {tab}}},\n')
        f.write("};\n")
        f.write(f"static const char *const OPS[] = {{{', '.join(chr(34) + o + chr(34) for o in BINARY + SHIFTS + FUNNEL + UNARY)}}};\n")


if __name__ == "__main__":
    main()
