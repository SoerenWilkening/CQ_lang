#!/usr/bin/env python3
"""Derive the e2e stage-3 link command from the clang driver, once, at configure time.

WHY THIS EXISTS (bd dgn5). Stage 3 of run_slice.sh used to be a single
`clang s2.ll templates.a runtime.a -o slice`. That one command spawns THREE
processes -- the clang driver, `clang -cc1` (codegen), and `/usr/bin/ld` -- two
of which dyld-bind libclang-cpp.dylib (77MB) and libLLVM.dylib (140MB). Worse,
the driver passes `-lto_library .../libLTO.dylib` UNCONDITIONALLY, so ld dlopens
libLTO -> libLLVM (another 140MB) on every slice even though nothing here uses
LTO. MEASURED on a real lowered slice, 6 interleaved reps, uncontended:

    driver (clang does codegen + link)   0.74-0.94s
    clang -c  +  raw ld (this script)    0.35-0.44s
    clang -c alone (the floor)           0.27-0.30s

So the link itself is ~0.06-0.10s and ~0.39s/slice was pure driver overhead.

THE LINE IS DERIVED, NEVER HAND-WRITTEN. We ask the real driver what it would
do (`clang -### probe.o`) and keep its answer verbatim except for three removals
(see below). It is re-derived on every CMake reconfigure, so an SDK bump, a
platform-version change, or a new clang runtime path is picked up automatically.
The failure mode of a stale line is a LOUD link error, never a wrong binary.

WHAT WE STRIP, AND WHY EACH IS SAFE:
  -lto_library <path>   the entire point -- nothing in the e2e pipeline uses LTO
                        (stage 3 is deliberately -O0; see the bd szpr pin), and
                        this arg exists only so ld can dlopen libLTO on demand.
  -mllvm <opt>          `-enable-linkonceodr-outlining`, an LTO-codegen knob
                        that is inert without libLTO loaded.
  -o <path> / probe.o   placeholders from the probe; the caller supplies the
                        real ones.

ON THE `-platform_version` WARNINGS. Linking emits
`ld: warning: object file ... was built for newer 'macOS' version (26.0) than
being linked (16.0)` because the runtime archives are compiled by CMake's
/usr/bin/cc (Apple clang, minos 26.0) while stage-3 objects come from Homebrew
clang 19 (minos 16.0). MEASURED: the ORIGINAL clang-driver link emits those same
three warnings today, and passes the same `-platform_version macos 16.0.0 26.4`.
This script therefore introduces NO new drift on that axis -- it reproduces the
driver's own values. Do not "fix" it by inventing a platform version here.
"""
import re
import shlex
import subprocess
import sys
import tempfile
import os

DROP_PAIRS = ("-lto_library", "-mllvm", "-o")


def derive(clang):
    """-> (head_tokens, tail_tokens). Caller's args go between them."""
    with tempfile.TemporaryDirectory() as td:
        probe_o = os.path.join(td, "cq_link_probe.o")
        probe_x = os.path.join(td, "cq_link_probe.out")
        subprocess.run([clang, "-x", "c", "-c", "/dev/null", "-o", probe_o],
                       check=True, capture_output=True)
        cp = subprocess.run([clang, "-###", probe_o, "-o", probe_x],
                            capture_output=True, text=True)
        # The driver prints its job list to stderr; the link job is the last line.
        lines = [l for l in cp.stderr.strip().split("\n") if l.strip()]
        if not lines:
            raise SystemExit("derive_link_line: clang -### produced no output")
        link = lines[-1]
        toks = re.findall(r'"([^"]*)"', link)
        if not toks or "ld" not in os.path.basename(toks[0]):
            raise SystemExit(
                "derive_link_line: last -### job is not a linker invocation: %r"
                % link[:200])

        head, tail, i, seen_out = [], [], 0, False
        while i < len(toks):
            t = toks[i]
            if t in DROP_PAIRS:
                if t == "-o":
                    seen_out = True
                i += 2
                continue
            if t == probe_o:
                seen_out = True   # everything after the input object is trailing libs
                i += 1
                continue
            (tail if seen_out else head).append(t)
            i += 1
        return head, tail


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: derive_link_line.py <clang> <out-wrapper.sh>")
    clang, out = sys.argv[1], sys.argv[2]
    head, tail = derive(clang)
    body = """#!/bin/sh
# GENERATED by tools/derive_link_line.py -- do not edit; re-run CMake instead.
# Links an e2e slice without paying the clang driver's ~0.39s of process spawns
# and libLTO/libLLVM dlopen. Usage: cq_link.sh -o <exe> <obj> [archives...]
exec {head} "$@" {tail}
""".format(head=" ".join(shlex.quote(t) for t in head),
           tail=" ".join(shlex.quote(t) for t in tail))
    with open(out, "w") as f:
        f.write(body)
    os.chmod(out, 0o755)
    print(out)


if __name__ == "__main__":
    main()
