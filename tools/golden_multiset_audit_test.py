PASS_STATUSES = ("SUBSTITUTION-ONLY", "AMBIGUOUS-d", "AMBIGUOUS-ca", "UNCHANGED")
FAIL_STATUSES = ("FINDING", "OUT-OF-SCOPE")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-v", "--verbose", action="store_true")
    cfg = ap.parse_args()
    fails = []
    v = cfg.verbose

    # ── layer 0: INDEPENDENCE ───────────────────────────────────────────────
    #
    # Textual identity on SOME case is fine — a shape whose handles renumber the
    # same way really does come out identical. What would make this whole file a
    # tautology is EVERY case being identical, i.e. the renderer having been
    # written by reading `reduce_3qlq` instead of the PRD. This layer measures
    # that, and also proves the audit's `normalise` is load-bearing rather than
    # comparing strings that were equal to begin with.
    print("=== layer 0: renderer / reducer INDEPENDENCE ===")
    n_diff = n_same = 0
    for name, prog, _want in positives():
        old, new = pair(prog)
        red, _c, arec = gma.reduce_3qlq(old)
        for idx, (a_rec, _b, _d) in arec.items():
            red[idx] = red[idx].replace(gma._A_TOKEN, gma._cfmt(a_rec))
        if red == new:
            n_same += 1
            continue
        n_diff += 1
        if arec:
            # A class-(d) case MUST disagree here and it is not a defect: the
            # reducer can only write `fl(B + D)`, which is one ulp off the true
            # source angle on the flagship shape. That gap is the entire reason
            # `a_tolerance` exists, and layer 5 pins it from both sides.
            continue
        if gma.normalise(red) != gma.normalise(new):
            fails.append("INDEPENDENCE %s: the hand renderer and reduce_3qlq "
                         "disagree even after handle normalisation — one of "
                         "the two does not implement PRD §10.2" % name)
    if n_diff == 0:
        fails.append("INDEPENDENCE: the hand renderer agreed TEXTUALLY with "
                     "reduce_3qlq on every case — the positives would pass by "
                     "construction and this file would prove nothing")
    print("  %d of %d positive case(s) differ textually from reduce_3qlq's "
          "output and agree only after handle normalisation (%d identical)"
          % (n_diff, len(positives()), n_same))

    # ── layer 1: POSITIVES ──────────────────────────────────────────────────
    print("\n=== layer 1: POSITIVE matrix (must NOT be a finding) ===")
    pos = positives()
    for name, prog, want in pos:
        old, new = pair(prog)
        st, detail, _r, _a, _g = gma.audit_pair_3qlq(old, new)
        ok = st in want
        if not ok:
            fails.append("POSITIVE %s: got %s, want %s\n%s"
                         % (name, st, "/".join(want), detail))
        if v or not ok:
            print("  %-28s %-18s %s" % (name, st, "ok" if ok else "*** WRONG ***"))
    print("  %d positive case(s), %d failure(s)"
          % (len(pos), sum(1 for f in fails if f.startswith("POSITIVE"))))

    # ── layer 2: NAMED MUTANTS ──────────────────────────────────────────────
    print("\n=== layer 2: NAMED mutants (every one must be a FINDING) ===")
    nm = named_mutants()
    for name, old, new, note in nm:
        st, detail, _r, _a, _g = gma.audit_pair_3qlq(old, new)
        ok = st in FAIL_STATUSES
        if not ok:
            fails.append("MUTANT %s SURVIVED as %s (%s)\n%s"
                         % (name, st, note, detail))
        print("  %-44s %-18s %s" % (name, st,
                                    "DETECTED" if ok else "*** SURVIVED ***"))
        if v:
            print("      why it matters: %s" % note)

    # ── layer 3: the LINE SWEEP ─────────────────────────────────────────────
    print("\n=== layer 3: LINE SWEEP over every positive new trace ===")
    n_sweep = 0
    for name, prog, want in pos:
        if "UNCHANGED" in want:
            continue          # a no-rz pair has nothing to sweep meaningfully
        old, new = pair(prog)
        for i in range(len(new)):
            for how, mutated in (("delete", _drop(new, i)),
                                 ("duplicate", new[:i] + [new[i]] + new[i:])):
                n_sweep += 1
                st, _d, _r, _a, _g = gma.audit_pair_3qlq(old, mutated)
                if st not in FAIL_STATUSES:
                    fails.append("SWEEP %s: %s line %d (%r) left the audit at %s"
                                 % (name, how, i + 1, new[i], st))
    print("  %d swept mutant(s), %d failure(s)"
          % (n_sweep, sum(1 for f in fails if f.startswith("SWEEP"))))

    # ── layer 4: the audit's OWN embedded families, driven quietly ──────────
    print("\n=== layer 4: the audit's embedded --selftest families ===")
    n_emb = 0
    for cname, o, n, want in gma._q_controls():
        n_emb += 1
        st, detail, _r, _a, _g = gma.audit_pair_3qlq(o, n)
        if st not in want:
            fails.append("EMBEDDED control %s: got %s want %s" % (cname, st, want))
    probes, inside, outside, _arec, _d = gma._q_probes()
    for pname, o, n in probes:
        n_emb += 1
        st, _detail, _r, _a, _g = gma.audit_pair_3qlq(o, n)
        if st not in FAIL_STATUSES:
            fails.append("EMBEDDED mutant %s SURVIVED as %s" % (pname, st))
    for mname, o, n in gma._mutants():                      # the 2a family
        n_emb += 1
        st, _detail, _r, _a, _g = gma.audit_pair(o, n)
        if st == "COLLAPSE-ONLY":
            fails.append("EMBEDDED 2a mutant %s SURVIVED" % mname)
    for cname, o, n, want in (("2a diamond", gma._OLD_DIAMOND, gma._NEW_DIAMOND,
                               "COLLAPSE-ONLY"),
                              ("2a ifne", gma._OLD_IFNE, gma._NEW_IFNE,
                               "COLLAPSE-ONLY"),
                              ("2a seq", gma._OLD_SEQ, gma._NEW_SEQ,
                               "COLLAPSE-ONLY"),
                              ("2a nest unchanged", gma._OLD_NEST, gma._OLD_NEST,
                               "UNCHANGED")):
        n_emb += 1
        st, _detail, _r, _a, _g = gma.audit_pair(o, n)
        if st != want:
            fails.append("EMBEDDED 2a control %s: got %s want %s"
                         % (cname, st, want))
    # The 2a SCOPE PROBE (L3 F1): a 4.3 nest whose INNER region collapsed.
    # ⚠ It does NOT pin `match_route_region`'s `base in rails_set` fence, and
    # saying it did would be the kind of unmeasured claim this project keeps
    # catching. MEASURED (2026-09-05): deleting that fence reddens NOTHING in
    # this file, because `out_of_scope_signature`'s S1 answers the same question
    # one layer earlier and owns the verdict, and the 3qlq reducer reaches an
    # inner region through `match_nest` (which pins the base itself) rather than
    # through the fence. What the fence still changes is the REPORTED region
    # count, which is what its own docstring measured. The row below is worth
    # keeping on its own terms — it is the only assertion anywhere that a
    # collapsed nested inner region is refused — but it is not that fence's probe.
    n_emb += 1
    st, _detail, _r, _a, _g = gma.audit_pair(gma._OLD_NEST,
                                             gma._NEW_NEST_INNER_COLLAPSED)
    if st == "COLLAPSE-ONLY":
        fails.append("EMBEDDED 2a scope probe SURVIVED: a 4.3 nest's inner "
                     "region collapsed and the audit blessed it")
    print("  %d embedded case(s) re-driven (3qlq controls + mutants + the whole "
          "2a family), %d failure(s)"
          % (n_emb, sum(1 for f in fails if f.startswith("EMBEDDED"))))

    # ── layer 5: the class-(d) tolerance, pinned from BOTH sides ────────────
    print("\n=== layer 5: the class-(d) tolerance, pinned from both sides ===")
    D_prog = [("reg", 0, "i32", "3", "0x1p-1"), ("reg", 1, "i32", "7", "0x1p-2"),
              ("angsel", 1, "i32", 0, "eq", 5, 0.3, 0.9)]
    D_old, D_new = pair(D_prog)
    n_tol = 0
    for label, a_val, want_pass in (("largest in-tolerance A", inside, True),
                                    ("one step further", outside, False)):
        n_tol += 1
        mut = [l.replace(gma._cfmt(0.9), gma._cfmt(a_val)) for l in D_new]
        st, _d, _r, _a, _g = gma.audit_pair_3qlq(D_old, mut)
        got = st in PASS_STATUSES
        if got != want_pass:
            fails.append("TOLERANCE %s: got %s (err %.4e, tol %.4e)"
                         % (label, st, abs(a_val - (0.3 + (0.9 - 0.3))),
                            gma.a_tolerance(a_val, 0.9 - 0.3)))
        print("  %-30s %-18s %s" % (label, st, "ok" if got == want_pass
                                    else "*** WRONG ***"))

    # ── layer 6: every REPORT check is a live wire, not decoration ──────────
    #
    # MEASURED (kill test, 2026-09-05, counting failures OUTSIDE this layer):
    # disabling (A), (A2), (A3), (A4), (A5) or (D) changes NO verdict in this
    # file, while disabling (B) changes 11. (B) is line-for-line after handle
    # normalisation, so it implies them all. They exist to NAME what moved, and
    # as a real net if (B) is ever weakened: with (B) off they still catch all
    # but six mutants — and those six are ALL handle-identity / order defects,
    # exactly the class a handle-INVARIANT multiset is blind to.
    #
    # ⚠ ONE PAIR IS ONLY JOINTLY PINNED and is recorded rather than hidden:
    # mutant n28 is caught by `match_nest`'s `len(arms) != 1` refusal (through
    # (B)) OR by (A4)'s cswap accounting, and deleting BOTH lets it through as
    # SUBSTITUTION-ONLY (measured). That is the `CLAUDE.md` "a predicate with
    # three arms and one probe" shape; it is a known limit of this file, not a
    # claim that every arm is individually pinned.
    #
    # A check that never fires would still be dead code, so this layer pins each
    # one to a mutant that makes it FALSE and to a positive that leaves it TRUE.
    # Deleting any report check turns THIS layer red even though (except for the
    # n28 pair above) it would not change a single verdict.
    print("\n=== layer 6: each REPORT check fires on its own mutant ===")
    ctrl_prog = [("reg", 0, "i32", "3", "0x1p-1"),
                 ("nest", 0, "i32", "sgt", 5, ("0x1p-2",), "slt", 9,
                  ("0x1.8p-1",), False, False),
                 ("meas", 0, "i32", "0")]
    ctrl_old, ctrl_new = pair(ctrl_prog)
    by_name = {n.split()[0]: (o, x) for n, o, x, _note in nm}
    wire = [("a", "n3"), ("ry", "n7"), ("rz", "n24"), ("cs", "n6"),
            ("tf", "n15"), ("d", "n8"), ("b", "n11"), ("scope", "n26")]
    n_wire = 0
    for key, mut in wire:
        n_wire += 1
        o, x = by_name[mut]
        cks = {}
        gma.audit_pair_3qlq(o, x, checks_out=cks)
        if cks.get(key, True):
            fails.append("WIRE: check (%s) stayed TRUE on mutant %s — it is "
                         "decoration, not a check" % (key, mut))
        cks2 = {}
        gma.audit_pair_3qlq(ctrl_old, ctrl_new, checks_out=cks2)
        if not cks2.get(key, False):
            fails.append("WIRE: check (%s) is FALSE on a correct nest "
                         "regeneration — a false alarm" % key)
        if v:
            print("  (%-5s) false on %s, true on the nest control" % (key, mut))
    print("  %d check(s) pinned from both sides, %d failure(s)"
          % (n_wire, sum(1 for f in fails if f.startswith("WIRE"))))

    print("\ngolden_multiset_audit_test: %d positive(s), %d named mutant(s), "
          "%d swept mutant(s), %d embedded case(s), %d tolerance pin(s), "
          "%d check-wire pin(s), %d failure(s)"
          % (len(pos), len(nm), n_sweep, n_emb, n_tol, n_wire, len(fails)))
    for x in fails:
        print("  FAIL " + x, file=sys.stderr)
    return 1 if fails else 0


