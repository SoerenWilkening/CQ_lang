# THE INDEPENDENT RENDERER
#
# A tiny program description is rendered TWICE — once as a pre-3qlq (OLD) trace
# and once as the post-3qlq (NEW) trace PRD §3 calls for. Handles are numbered
# independently in each rendering, exactly as two different compiler runs would
# number them, so the audit's `normalise` is exercised on every case rather than
# being bypassed by identical numbering.
#
# Ops (a `prog` is a list of them):
#   ("reg",    rid, W, seed, ry_theta)          allocate + Ry a register
#   ("phase",  rid, W, pred, k, arms, style)    a tainted-condition phase region
#                                               style "routed" = the pre-2a swap
#                                               route (class b); style "inplace"
#                                               = the shipped 2a form (class a).
#                                               arms = [(thetas, negated), …]
#   ("nest",   rid, W, po, ko, tho, pi, ki, thi, nego, negi)   the 4.3 depth-2 nest
#   ("uncond", rid, W, thetas)                  uncontrolled Rz lines (class c)
#   ("angsel", rid, W, crid, pred, k, B, A)     the drbq Inc-2b pair (class d)
#   ("other",  line)                            any verbatim non-Rz line
#   ("meas",   rid, W, ret)                     a measurement
# ═════════════════════════════════════════════════════════════════════════════

def _mint(pred, W, base, k, flag):
    return "cq_template_icmp_%s_%s_hl(%s, %s) -> %s" % (pred, W, base, k, flag)


def _strip(pred, W, flag, base, k):
    return "cq_template_icmp_%s_%s_hl_unc(%s, %s, %s)" % (pred, W, flag, base, k)


def render(prog, mode):
    """-> the trace lines for `prog`. `mode` is "old" (pre-3qlq) or "new"."""
    assert mode in ("old", "new")
    R, out, n = {}, [], [0]

    def h():
        n[0] += 1
        return "h%d" % (n[0] - 1)

    for op in prog:
        t = op[0]
        if t == "reg":
            _, rid, W, seed, ry = op
            R[rid] = h()
            out.append("cqrt_alloc_%s(%s) -> %s" % (W, seed, R[rid]))
            if ry is not None:
                out.append("cqrt_ry_%s(%s, %s)" % (W, R[rid], ry))
        elif t == "other":
            out.append(op[1])
        elif t == "meas":
            _, rid, W, ret = op
            out.append("cqrt_measure_%s(%s) -> %s" % (W, R[rid], ret))
        elif t == "uncond":
            _, rid, W, thetas = op
            if mode == "old":                      # (c): DELETED in the new trace
                for th in thetas:
                    out.append("cqrt_rz_%s(%s, %s)" % (W, R[rid], th))
        elif t == "phase":
            _, rid, W, pred, k, arms, style = op
            b = R[rid]
            f = h()
            out.append(_mint(pred, W, b, k, f))
            if mode == "old" and style == "routed":
                rails = [h() for _ in arms]
                for (_th, _ng), r in zip(arms, rails):
                    out.append("cqrt_alloc_%s(0) -> %s" % (W, r))
                for (_th, ng), r in zip(arms, rails):
                    if ng:
                        out.append("cqrt_x(%s)" % f)
                    out.append("cqrt_cswap(%s, %s, %s)" % (f, b, r))
                    if ng:
                        out.append("cqrt_x(%s)" % f)
                for (th, _ng), r in zip(arms, rails):
                    for x in th:
                        out.append("cqrt_rz_%s(%s, %s)" % (W, r, x))
                for (_th, ng), r in zip(arms, rails):
                    if ng:
                        out.append("cqrt_x(%s)" % f)
                    out.append("cqrt_cswap(%s, %s, %s)" % (f, b, r))
                    if ng:
                        out.append("cqrt_x(%s)" % f)
                for r in rails:
                    out.append("cqrt_free(%s)" % r)
            elif mode == "old":                    # style "inplace" — the 2a form
                for (th, ng) in arms:
                    if ng:
                        out.append("cqrt_x(%s)" % f)
                    for x in th:
                        out.append("cqrt_rz_%s_controlled(%s, %s, %s)" % (W, f, b, x))
                    if ng:
                        out.append("cqrt_x(%s)" % f)
            else:                                  # the KICKBACK form (PRD §3)
                for (th, ng) in arms:
                    if ng:
                        out.append("cqrt_x(%s)" % f)
                    for x in th:
                        out.append("cqrt_rz_i1(%s, %s)" % (f, x))
                    if ng:
                        out.append("cqrt_x(%s)" % f)
            out.append(_strip(pred, W, f, b, k))
            out.append("cqrt_free(%s)" % f)
        elif t == "nest":
            _, rid, W, po, ko, tho, pi, ki, thi, nego, negi = op
            b = R[rid]
            fa = h()
            out.append(_mint(po, W, b, ko, fa))
            if mode == "old":
                w1 = h()
                out.append("cqrt_alloc_%s(0) -> %s" % (W, w1))
                for _ in range(2 if nego else 0):
                    pass
                if nego:
                    out.append("cqrt_x(%s)" % fa)
                out.append("cqrt_cswap(%s, %s, %s)" % (fa, b, w1))
                if nego:
                    out.append("cqrt_x(%s)" % fa)
                for x in tho:
                    out.append("cqrt_rz_%s(%s, %s)" % (W, w1, x))
                fb = h()
                out.append(_mint(pi, W, w1, ki, fb))
                w2 = h()
                out.append("cqrt_alloc_%s(0) -> %s" % (W, w2))
                if negi:
                    out.append("cqrt_x(%s)" % fb)
                out.append("cqrt_cswap(%s, %s, %s)" % (fb, w1, w2))
                if negi:
                    out.append("cqrt_x(%s)" % fb)
                for x in thi:
                    out.append("cqrt_rz_%s(%s, %s)" % (W, w2, x))
                if negi:
                    out.append("cqrt_x(%s)" % fb)
                out.append("cqrt_cswap(%s, %s, %s)" % (fb, w1, w2))
                if negi:
                    out.append("cqrt_x(%s)" % fb)
                out.append("cqrt_free(%s)" % w2)
                out.append(_strip(pi, W, fb, w1, ki))
                out.append("cqrt_free(%s)" % fb)
                if nego:
                    out.append("cqrt_x(%s)" % fa)
                out.append("cqrt_cswap(%s, %s, %s)" % (fa, b, w1))
                if nego:
                    out.append("cqrt_x(%s)" % fa)
                out.append("cqrt_free(%s)" % w1)
            else:
                if tho and nego:
                    out.append("cqrt_x(%s)" % fa)
                for x in tho:
                    out.append("cqrt_rz_i1(%s, %s)" % (fa, x))
                if tho and nego:
                    out.append("cqrt_x(%s)" % fa)
                fb = h()
                out.append(_mint(pi, W, b, ki, fb))   # the RAIL is gone: w1 -> b
                g = h()
                out.append("cqrt_alloc_i1(0) -> %s" % g)
                for p in range(2):
                    if negi:
                        out.append("cqrt_x(%s)" % fb)
                    out.append("cqrt_toffoli(%s, %s, %s)" % (fa, fb, g))
                    if negi:
                        out.append("cqrt_x(%s)" % fb)
                    if p == 0:
                        for x in thi:
                            out.append("cqrt_rz_i1(%s, %s)" % (g, x))
                out.append("cqrt_free(%s)" % g)
                out.append(_strip(pi, W, fb, b, ki))
                out.append("cqrt_free(%s)" % fb)
            out.append(_strip(po, W, fa, b, ko))
            out.append("cqrt_free(%s)" % fa)
        elif t == "angsel":
            _, rid, W, crid, pred, k, B, A = op
            b, c = R[rid], R[crid]
            d = gma._cfmt(A - B)
            if mode == "old":
                out.append("cqrt_rz_%s(%s, %s)" % (W, b, gma._cfmt(B)))
                f = h()
                out.append(_mint(pred, W, c, k, f))
                out.append("cqrt_rz_%s_controlled(%s, %s, %s)" % (W, f, b, d))
            else:
                f = h()
                out.append(_mint(pred, W, c, k, f))
                out.append("cqrt_x(%s)" % f)
                out.append("cqrt_rz_i1(%s, %s)" % (f, gma._cfmt(B)))
                out.append("cqrt_x(%s)" % f)
                out.append("cqrt_rz_i1(%s, %s)" % (f, gma._cfmt(A)))
            out.append(_strip(pred, W, f, c, k))
            out.append("cqrt_free(%s)" % f)
        else:
            raise AssertionError("unknown op %r" % (op,))
    return out


def pair(prog):
    return render(prog, "old"), render(prog, "new")


