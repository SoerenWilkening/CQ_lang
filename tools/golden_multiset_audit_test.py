def _drop(L, i):
    L = list(L)
    del L[i]
    return L


def _swap(L, a, b):
    L = list(L)
    L[a], L[b] = L[b], L[a]
    return L


def _mv(L, frm, to):
    L = list(L)
    L.insert(to, L.pop(frm))
    return L


def _first(L, sub):
    return next(i for i, l in enumerate(L) if sub in l)


def _last(L, sub):
    return len(L) - 1 - next(i for i, l in enumerate(reversed(L)) if sub in l)


