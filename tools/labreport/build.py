#!/usr/bin/env python3
"""Build the owner-facing lab report (docs/labreport/labreport.pdf) and enforce
its three MECHANICAL rules. The prose rules live in docs/labreport/README.md and
CLAUDE.md ("Lab report"); this script is what makes them checkable.

  1. APPEND-ONLY. Every file listed in docs/labreport/MANIFEST.sha256 must exist
     and hash identically. A sealed session entry (and its figures/NNN/ files) is
     byte-immutable; a correction is a dated erratum in a LATER entry.
  2. PAGE BUDGET. Each session entry is at most MAX_PAGES pages, measured from
     the labels \labsession writes into the .aux, unless the entry declares
     `% labreport-page-budget-exempt: <reason>` (the one-time baseline does).
  3. ORDER. sessions.tex is REGENERATED from sessions/*.tex (sorted); names must
     match NNN-YYYY-MM-DD-slug.tex with NNN consecutive from 001.

Usage:
  tools/labreport/build.py            # verify manifest, build PDF, check budgets
  tools/labreport/build.py --seal     # ...then seal every unsealed entry/figure
  tools/labreport/build.py --no-build # rules 1 and 3 only (no TeX)

Exit non-zero on any violation. The PDF and build/ are gitignored: sources are
committed, the PDF is built locally (owner decision 2026-09-10).
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / "docs" / "labreport"
SESSIONS = ROOT / "sessions"
FIGURES = ROOT / "figures"
MANIFEST = ROOT / "MANIFEST.sha256"
SESSIONS_TEX = ROOT / "sessions.tex"
BUILD = ROOT / "build"
MAIN = "labreport"
MAX_PAGES = 5
NAME_RE = re.compile(r"^(\d{3})-(\d{4}-\d{2}-\d{2})-([a-z0-9][a-z0-9-]*)\.tex$")
EXEMPT_RE = re.compile(r"^%\s*labreport-page-budget-exempt:\s*(.+)$", re.M)


def die(msg: str) -> None:
    print(f"labreport: ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def session_files() -> list[Path]:
    files = sorted(SESSIONS.glob("*.tex"))
    if not files:
        die(f"no session entries in {SESSIONS}")
    for i, f in enumerate(files, start=1):
        m = NAME_RE.match(f.name)
        if not m:
            die(f"bad session file name {f.name}: want NNN-YYYY-MM-DD-slug.tex")
        if int(m.group(1)) != i:
            die(f"session numbering is not consecutive at {f.name} (expected {i:03d})")
    return files


def regenerate_sessions_tex(files: list[Path]) -> None:
    body = "% GENERATED by tools/labreport/build.py from sessions/*.tex -- do not edit.\n"
    body += "".join(f"\\labsession{{{f.stem}}}\n" for f in files)
    if not SESSIONS_TEX.exists() or SESSIONS_TEX.read_text() != body:
        SESSIONS_TEX.write_text(body)
        print(f"labreport: regenerated {SESSIONS_TEX.relative_to(REPO)} ({len(files)} entries)")


def sealed_entries() -> dict[str, str]:
    if not MANIFEST.exists():
        return {}
    out: dict[str, str] = {}
    for ln in MANIFEST.read_text().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        digest, rel = ln.split(None, 1)
        out[rel.strip()] = digest
    return out


def sealable_files() -> list[str]:
    rels = [str(p.relative_to(ROOT)) for p in SESSIONS.glob("*.tex")]
    if FIGURES.exists():
        rels += [str(p.relative_to(ROOT)) for p in FIGURES.rglob("*") if p.is_file() and p.name != ".gitkeep"]
    return sorted(rels)


def verify_manifest() -> list[str]:
    sealed = sealed_entries()
    bad = []
    for rel, digest in sealed.items():
        p = ROOT / rel
        if not p.exists():
            bad.append(f"sealed file MISSING: {rel}")
        elif sha256(p) != digest:
            bad.append(f"sealed file MODIFIED: {rel} (append-only: write an erratum in a later entry)")
    if bad:
        die("\n  " + "\n  ".join(bad))
    unsealed = [r for r in sealable_files() if r not in sealed]
    print(f"labreport: manifest OK ({len(sealed)} sealed, {len(unsealed)} unsealed)")
    for r in unsealed:
        print(f"labreport:   unsealed: {r}")
    return unsealed


def run_tex() -> None:
    BUILD.mkdir(exist_ok=True)
    env = dict(os.environ, TEXINPUTS=f"{ROOT}{os.pathsep}")
    if shutil.which("latexmk"):
        cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error",
               "-file-line-error", f"-outdir={BUILD}", f"{MAIN}.tex"]
        runs = [cmd]
    elif shutil.which("pdflatex"):
        cmd = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
               "-file-line-error", f"-output-directory={BUILD}", f"{MAIN}.tex"]
        runs = [cmd, cmd, cmd]
    else:
        die("neither latexmk nor pdflatex on PATH (TeX Live: /Library/TeX/texbin)")
    for c in runs:
        r = subprocess.run(c, cwd=ROOT, env=env, capture_output=True, text=True)
        if r.returncode != 0:
            log = BUILD / f"{MAIN}.log"
            tail = log.read_text(errors="replace").splitlines()[-40:] if log.exists() else r.stdout.splitlines()[-40:]
            die("TeX failed:\n  " + "\n  ".join(tail))
    pdf = BUILD / f"{MAIN}.pdf"
    if not pdf.exists():
        die("TeX reported success but produced no PDF")
    shutil.copyfile(pdf, ROOT / f"{MAIN}.pdf")


def _balanced_groups(s: str, start: int) -> list[str]:
    """Return the top-level {...} groups of s starting at s[start] == '{' ... until the
    enclosing group closes. s[start-1] is the '{' that opens the enclosing group."""
    groups, depth, cur = [], 0, []
    i = start
    while i < len(s):
        ch = s[i]
        if ch == "{":
            depth += 1
            if depth > 1:
                cur.append(ch)
        elif ch == "}":
            if depth == 0:
                break
            depth -= 1
            if depth == 0:
                groups.append("".join(cur))
                cur = []
            else:
                cur.append(ch)
        else:
            if depth >= 1:
                cur.append(ch)
        i += 1
    return groups


def label_pages() -> dict[str, int]:
    aux = BUILD / f"{MAIN}.aux"
    if not aux.exists():
        die("no .aux after build")
    pages: dict[str, int] = {}
    text = aux.read_text(errors="replace")
    for m in re.finditer(r"\\newlabel\{(labsess:[^}]*)\}\{", text):
        groups = _balanced_groups(text, m.end())
        if len(groups) < 2:
            die(f"cannot parse page for label {m.group(1)}")
        try:
            pages[m.group(1)] = int(groups[1])
        except ValueError:
            die(f"non-numeric page for label {m.group(1)}: {groups[1]!r}")
    return pages


def check_budgets(files: list[Path], sealed: set[str]) -> None:
    """Enforce MAX_PAGES on UNSEALED entries only. A sealed entry was within budget
    when sealed; a later preamble/font change that reflows it must not make the
    report unbuildable, so for sealed entries the count is reported, not judged."""
    pages = label_pages()
    rows, bad = [], []
    for f in files:
        s, e = pages.get(f"labsess:{f.stem}:start"), pages.get(f"labsess:{f.stem}:end")
        if s is None or e is None:
            die(f"missing start/end page labels for {f.stem} (is it listed in sessions.tex?)")
        n = e - s + 1
        is_sealed = str(f.relative_to(ROOT)) in sealed
        exempt = EXEMPT_RE.search(f.read_text())
        status = "ok (sealed)" if is_sealed else "ok"
        if n > MAX_PAGES:
            if is_sealed:
                status = f"over {MAX_PAGES} after reflow (sealed; not judged)"
            elif exempt:
                status = f"EXEMPT ({exempt.group(1).strip()})"
            else:
                status = f"OVER BUDGET (> {MAX_PAGES})"
                bad.append(f.stem)
        rows.append((f.stem, s, e, n, status))
    w = max(len(r[0]) for r in rows)
    print("labreport: page budgets")
    for stem, s, e, n, status in rows:
        print(f"  {stem:<{w}}  pp. {s:>3}-{e:<3}  {n:>2} page(s)  {status}")
    if bad:
        die(f"{len(bad)} entr{'y' if len(bad) == 1 else 'ies'} over the {MAX_PAGES}-page budget: {', '.join(bad)}")


def seal(unsealed: list[str]) -> None:
    if not unsealed:
        print("labreport: nothing to seal")
        return
    lines = [] if not MANIFEST.exists() else MANIFEST.read_text().splitlines()
    if not lines:
        lines = ["# SHA-256 of sealed lab-report files (append-only; verified by tools/labreport/build.py).",
                 "# A sealed file is never edited: corrections are dated errata in a later entry."]
    for rel in unsealed:
        lines.append(f"{sha256(ROOT / rel)}  {rel}")
    MANIFEST.write_text("\n".join(lines) + "\n")
    print(f"labreport: sealed {len(unsealed)} file(s) into {MANIFEST.relative_to(REPO)}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seal", action="store_true", help="after a successful build, seal unsealed entries/figures")
    ap.add_argument("--no-build", action="store_true", help="manifest + naming checks only")
    a = ap.parse_args()
    files = session_files()
    regenerate_sessions_tex(files)
    unsealed = verify_manifest()
    if a.no_build:
        return 0
    run_tex()
    check_budgets(files, set(sealed_entries()))
    pdf = ROOT / f"{MAIN}.pdf"
    if shutil.which("pdfinfo"):
        info = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True).stdout
        m = re.search(r"^Pages:\s+(\d+)", info, re.M)
        print(f"labreport: built {pdf.relative_to(REPO)} ({m.group(1) if m else '?'} pages)")
    else:
        print(f"labreport: built {pdf.relative_to(REPO)}")
    if a.seal:
        seal(unsealed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
