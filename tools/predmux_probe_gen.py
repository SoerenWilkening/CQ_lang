def emit(outdir: str) -> int:
    os.makedirs(outdir, exist_ok=True)
    for p in PROBES:
        text = HEADER.format(desc=p['desc'], decls=p['decls'],
                             globals=p['globs']) + '\n' + BODY.format(
            seed=p['seed'], seedval=p['seedval'], shielded=p['shielded'])
        with open(os.path.join(outdir, p['name'] + '.ll'), 'w') as fh:
            fh.write(text)
    print(f'emitted {len(PROBES)} probes to {outdir}')
    return 0


def run_opt(plugin: str, src: str, dst: str):
    r = subprocess.run(
        [OPT, '-load-pass-plugin', plugin, '-passes=cq-lowering', '-S', src,
         '-o', dst], capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


def accepted(rc: int, err: str, out_path: str):
    """Reach gate: claimed AND flattened.  Returns (bool, reason)."""
    if rc != 0:
        return False, f'opt exit {rc}'
    if 'cq ' in err and 'error' in err:
        return False, 'loud decline: ' + err.strip().splitlines()[0][:110]
    try:
        with open(out_path) as fh:
            out = fh.read()
    except OSError:
        return False, 'no output'
    if re.search(r'^\s*(%\S+ = )?(br i1|select i1)', out, re.M):
        return False, 'diamond NOT flattened (br i1/select i1 survive)'
    if 'cqrt_toffoli' not in out:
        return False, 'no cqrt_toffoli — the two-conjunct AND was never built'
    return True, 'claimed+flattened'


def measure(out_path: str, grep):
    """-> True if the probe's tracked property is PRESENT in the output."""
    if grep is None:
        return None
    line_rx, token = grep
    with open(out_path) as fh:
        for line in fh:
            if re.search(line_rx, line):
                return token in line
    return None    # the tracked line vanished entirely


def run(probedir: str, base: str, new: str | None) -> int:
    names = sorted(p['name'] for p in PROBES)
    by = {p['name']: p for p in PROBES}
    reach, noreach = [], []
    rows = []
    for n in names:
        src = os.path.join(probedir, n + '.ll')
        if not os.path.exists(src):
            print(f'  MISSING {n}.ll — run --emit first')
            return 2
        bo = os.path.join(probedir, n + '.BASE.out.ll')
        brc, berr = run_opt(base, src, bo)
        ok, why = accepted(brc, berr, bo)
        if not ok:
            noreach.append((n, why))
            continue
        reach.append(n)
        bprop = measure(bo, by[n]['grep'])
        nprop = nwhy = None
        if new:
            no = os.path.join(probedir, n + '.NEW.out.ll')
            nrc, nerr = run_opt(new, src, no)
            nok, nwhy = accepted(nrc, nerr, no)
            nprop = measure(no, by[n]['grep']) if nok else None
            same = nok and open(bo).read() == open(no).read()
            rows.append((n, bprop, nok, nprop, same, nwhy))
        else:
            rows.append((n, bprop, None, None, None, None))

    print('=' * 78)
    print(f'REACH GATE: {len(reach)}/{len(names)} probes ACCEPTED by BASE')
    print('  (a probe BASE does not accept proves NOTHING and is not counted)')
    for n, why in noreach:
        print(f'  NO-REACH  {n:32s} {why}')
    print('=' * 78)
    hdr = f'{"probe":34s} {"BASE prop":10s}'
    if new:
        hdr += f' {"NEW ok":7s} {"NEW prop":9s} {"identical":9s}'
    print(hdr)
    for r in rows:
        n, bprop, nok, nprop, same, nwhy = r
        s = f'{n:34s} {str(bprop):10s}'
        if new:
            s += f' {str(nok):7s} {str(nprop):9s} {str(same):9s}'
            if nok is False:
                s += f'   <- {nwhy}'
        print(s)
    print()
    print('EXPECTATIONS (read these against the table; the tool does not judge):')
    for n in names:
        if n in reach:
            print(f'  {n:34s} {by[n]["expect"]}')
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--emit', metavar='DIR')
    ap.add_argument('--run', metavar='DIR')
    ap.add_argument('--base', help='pinned pre-change plugin (.so)')
    ap.add_argument('--new', help='post-change plugin (.so)')
    a = ap.parse_args()
    if a.emit:
        return emit(a.emit)
    if a.run:
        if not a.base:
            ap.error('--run needs --base (the reach gate is not optional)')
        return run(a.run, a.base, a.new)
    ap.error('one of --emit / --run is required')


if __name__ == '__main__':
    sys.exit(main())
