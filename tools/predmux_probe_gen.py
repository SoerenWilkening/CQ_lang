#!/usr/bin/env python3
"""Reach-gated probe family for the PredMux shielded-cone poison fence.

WHY THIS IS COMMITTED
=====================
This family has now been hand-rebuilt three times, and one of those rebuilds
produced FOUR probes that proved nothing: they were written on a single-merge-phi
template, so the region died at an earlier gate and never reached the clause under
test, yet they were reported as passes.  The lesson is encoded here as a hard
rule rather than a habit:

    *** A PROBE COUNTS ONLY IF THE PRE-CHANGE PLUGIN ACCEPTS IT. ***

`--run` REACH-GATES every probe against the BASE plugin before comparing
anything.  A probe BASE does not accept is reported NO-REACH and is never
counted as a pass, a fail, or evidence of any kind.

WHAT "ACCEPT" MEANS HERE
========================
The region was CLAIMED and FLATTENED: `opt` exits 0, and the lowered module
contains no `br i1` / `select i1` (the diamond is gone) and at least one
`cqrt_toffoli` (the two-conjunct AND was physically built).  Both halves matter
— a module that never had a diamond also has no `br i1`.

THE TEMPLATE
============
Every probe is built on `control_predmux_accept_selectform_curated_total.ll`'s
shape: a tainted `cq_theta` rail, a poison-shielded `select i1 %a, i1 %b, i1
false` guard, a two-instruction arm, and — load-bearing — **TWO merge phis**.
One phi is not enough: the single-phi form dies at the W-witness gate before the
cone proof is ever consulted.

USAGE
=====
    python3 tools/predmux_probe_gen.py --emit /tmp/probes
    python3 tools/predmux_probe_gen.py --run /tmp/probes \\
        --base /path/BASE.so [--new /path/NEW.so]

With only `--base`, it reports the reach gate and each probe's observed
properties on that plugin.  With `--new` too, it reports the BASE-vs-NEW
difference per probe against that probe's declared EXPECTATION.
"""

